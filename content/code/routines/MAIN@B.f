C
C      MAYL LOG FILE
C     WRITTEN FOR NASA/LRC/SPO  BY DeKeHARRIS
C                                 HAMPTON SCOUT OFFICE
C                                 VOUGHT CORP.
C
       COMMON /COAT/CO
C      FILES FOR READING AND WRITING
C
C      FILE     FUNIT     FUNIT    DESCRIPTION
C      ITY      1         1        USERS TERMINAL.
C      TRAN     6         2        DATA  SUBFILE FOR TRANSMITTAL AND SPECFICATION
C      OUT      7         3        TEMPORARY  OUTPUT FILE
C      REVS     6         4        TEMPORARY  REVISION PATA FILE
C      INACTL   9         5         INACTIVE FILE FOR ARCHIVE RUN OF TRAN
C      INACTS   9         5         INACTIVE FILE FOR ARCHIVE RUN
C       AcTO    9           5         ACTION DUE FILE
C      DATE   10         6         TLMPORARY  DATE FILE
C      MEMO   11         7         DATA  SUBFILE FOR MEMOS AND LETTERS
C      TWEX   12         g         DATA SUBFILE  FOR TWXSeMAGNAFAXs& RAPIFAX
C      ANN    13         3          DATA SUBFILE FOR ANNOUNCEMENTS
C      PR     14        10         DATA  SUSFILE FOR PURCHASE REQUESTS
C      MIS    15        11          DATA SUBFILE FOR MISCELLANEOUS AND REPORTS
C
C      NOTE ONLY FILES TTYoREVSs AND DATE CFUNITS 198910) ARE OPENED HERE
C
       DOUBLE PRECISION CD
       INTEGER*2 DRFA,IPAS(3),IC

C
C  SYSCOM>KEYS.F      MNEMONIC KEYS FOR FILE SYSTEM (FTN)     31 MAY, 1977
       NOLIST
       CALL BREAK$ (FALSE o?          :
       CALL CLEAR
       CALL COMI(ETTY® e3,129IC)
       WRITE (1,100)
 100   FORMAT((C' WELCOME TO SPADS'/////,
     1   MAIL LOG FILE  ‘'%9/)
200   WRITE(1,250)
250   FORMAT(2X,' ',/,' DO YOU WISH TO WORK WITH THE DIR/REPORT DATA ',
     1 '--- ENTER DIR',/,26X,'OR DRAWING DATA',5X,'--- ENTER DRAW',/,26X
     1 ,'OR DAILY CORRESPONDENCE  --- COR',/,26X,'OR QUIT',
     118X,'--- QU')
      READ(1,11)IOPT
      IF(IOPT.EQ.'QU') GOTO 1200
      IF(IOPT.EQ.'CO') GOTO 800
      IPAS(1)='  '
      IPAS(2)='  '
      IPAS(3)='  '
      IF(IOPT.EQ.'DR') GOTO 700
      IF(IOPT.NE.'DI') GOTO 200
      CALL ATCH$$('F_DIR',5,K$ALLD,IPAS,K$IMFD+K$SETH,IC)
      CALL RESU$$('*DIR',4)
      CALL EXIT
700   CALL ATCH$$('F_DRAW',6,K$ALLD,IPAS,K$IMFD+K$SETH,IC)
      CALL RESU$$('*DRAW',5)
      CALL EXIT
800    CONTINUE
      CALL SRCH$$(K$RDWR+K$NDAM,'REVS  ',6,4,1,IC)
      IF(IC.NE.0) GOTO 1000
      CALL SRCH$$(K$RDWR+K$NDAM,'DATE  ',6,6,1,IC)
      IF(IC.NE.0) GOTO 1000
C
C      1000 IS THE ERROR HANDLER
C
C      IF THE PROGRAM REACHES THIS FAR THE FILES ARE OPEN AND USABLE
C
889   CALL CLEAR
      CALL IDENT
10    WRITE(1,2)
2     FORMAT(' PLEASE CHOSE ONE OF THE FOLLOWING ',/,
     1' MODE               KEY',/,
     1' INPUT              INP',/,
     1' REVISE             REV',/,
     1' SEARCH             SEA',/,
     1' ARCHIVE            ARC',/,
     1' QUIT               QUIT',//)
      REWIND 6
      REWIND 10
      READ(1,11)IOPT
11    FORMAT(1A2)
      IF(IOPT.EQ.'IN') CALL INPTC
      IF(IOPT.EQ.'RE') CALL REVSC
      IF(IOPT.EQ.'SE') CALL SEAC
      IF(IOPT.EQ.'AR') CALL ARCC
      IF(IOPT.EQ.'QU') GO TO 1100
      GO TO 10
1000  WRITE(1,1001)
1001  FORMAT(' SORRY - THE MAIL LOG FILE IS CURRENTLY IN USE',/,
     1' PLEASE TRY AGAIN LATER',///)
1100  CALL SRCH$$(K$CLOS,'REVS  ',6,0,0,0)
      CALL SRCH$$(K$CLOS,'DATE  ',6,0,0,0)
      GO TO 200
1200  CALL EXIT
      END
