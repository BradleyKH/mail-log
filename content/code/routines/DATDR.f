      SUBROUTINE DATDR
C
C     COMMON BLOCK FOR THE DIR FILE
C
      COMMON TIT,PTIT,DIR,RPT,DT,SYS,WAN,CON,ID,VEH,ACT,R
      COMMON COMP,REV,RDAT,WA
C
C
C     DATA DECLARATION BLOCK FOR THE DIR FILE
C
      INTEGER*4 TIT(21),PTIT(19),DIR(4),RPT(4),SYS(3),CON(5),ID,ACT
      INTEGER*4 COMP(21)
      INTEGER*2 DT(3),WAN(4),VEH(2,2),R,REV,RDAT(3),WA(4)
C
C
C
C     THIS ROUTINE LOCATED ALL DOCUMENTS WITH A SPECIFIED DATE
C
      INTEGER*2 D(3)
      KNT=0
20    WRITE(1,21)
21    FORMAT(' WHAT IS THE DATE THAT YOU WANT',/,'!MMDDYY!'/)
      READ(1,22,ERR=20)D
22    FORMAT(1X,3I2)
100   READ(6,END=200)TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
      IF(REV.EQ.'  ') GOTO 150
      IF(D(1).EQ.0) GO TO 110
      IF(D(1).NE.DT(1)) GO TO 100
110   IF(D(2).EQ.0) GO TO 120
      IF(D(2).NE.DT(2)) GO TO 100
120   IF(D(3).EQ.0) GO TO 130
      IF(D(3).NE.DT(3)) GO TO 100
130   CALL FMAIN
      KNT=KNT+1
      GO TO 100
150   IF(D(1).EQ.0) GOTO 160
      IF(D(1).NE.RDAT(1)) GOTO 100
160   IF(D(2).EQ.0) GOTO 170
      1F(0(2).NE.RDAT(2)) GOTO 100
170   IF(O(3)-E5-20) GOTO 130
      IF (D(3) -NE,RDAT(3)3) GOTO 100
      GO TO 130
C 200 WRITE C1 9250 KNT«D
250   FORMAT(' THERE ARE 'I19' DOCUMENTS WITH A DATE OF '2(12%=+') 612)
      RETURN
      END.
