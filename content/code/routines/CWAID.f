      SUBROUTINE CWAID
C      THIS SUBROUTINE PERFORMS THE WA NUMBER/ID CODE SEARCH
C
C     DATA DECLARATION AND COMMON BLOCK FOR THE MAIL LOG FILE
C
      COMMON/BLK/ MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,
     1    ADD,TWX,FSC,NRE,DDT,R,PTIT,COUNT,CON
      COMMON/SRC/ KNT,DM,DA,DDD,DTO,DL,IT,D,WA,DW,DT,DRE
     1     ,TFVD,TLVD,FVD,LVD,IEX
      COMMON/FLA/ ITRSP,IMELE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*4 ATHR(7),TO(8),DLN(5),SUB(21),ROUT(6),PTIT(19),
     1         CON(5),TWX(6,5),FSC(6),NRE(1,3),DDT(30,21),T(21)          ! [?]
     1       ,TIT(24),COUNT,CONT(5),IEX(4,3)
      INTEGER*2 MS,DD(3),IDD(3),ADD(3),R,CWA(4),WA(4)
      INTEGER*2 ITRSP,IMELE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*2 FVD(3),LVD(3),D(3),DM,DDD(3)
      INTEGER*4 DRE,DT(5),DW(5),DL(5),DA(7),IT(24),DTO(8),KNT
      DOUBLE PRECISION DTJ,TF,TL,TJUL,TFVD,TLVD,TIM,TJ
      INTEGER*2 IPAGE,IPRINT
C      INITIALIZE COUNTER
      KNT=0
C      INITIALIZE FIRST FOUND FLAG
      IPAGE=0
C      INITIALIZE TOP OF PRINTER PAGE FLAG
       IPRINT=0
3     WRITE(1,1)
1     FORMAT('  W.A. NUMBER/ID. CODE SEARCH',/,
     1' WHAT IS THE DESIRED CODE'/)
      READ(1,2,ERR=3)WA
2     FORMAT(4A2)
C      READ DOCUMENT RECORD OF THE APPROPRIATE SUB-FILE
100   CALL RDSUB
C      IS THE SEARCH COMPLETED ON ALL SELECTED SUB-FILES
       IF(IREAD.EQ.1) GOTO 200
      IM=IDD(1)
      ID=IDD(2)
      IY=IDD(3)
      CALL JTIME(IY,IM,ID,0,0,0,TIM)
C     LECTEVDeLTeTIMeANDeTIMeLEeTLVDIGO TO 890
      GO TO 100
890   CONTINUE
      IFCWA(G)ONES*®    GOTO 5
      IFCWA(3).NE.®     GOTO 40
      DO 30 1=1e02
      IF(WA(I)SNE,CWA(I)) GO TO 160
30    CONTINUE
      GO TO 150
40    DO 50 12193
      IF(WACTISME,CWA(T)) GOTO 100
50    CONTINUE
      GO TO 150
5     06 16 1=104
      IF(WA(T).NE.CWACI?) GOTO 100
10    CONTINUE
C      WA NUMBER / ID CODE FOUND                                 .
C      IS THIS THE FIRST RECORD FOUND
150   IF(IPAGE.NE.0) GOTO 16C
C  ... SET UP FOR DISFLAY ON TERMINAL
      ITEM=9
      IPAGE=1
C      DISPLAY HEADING ON TERMINAL FOR WA NUMBER/ID CODE:
      CALL SCRNHD(ITEM)
C      OISPLAY RECORD OF DOCUMENT FOUND)
160   CALL. SCRNPT(ITEM)
C      IS THIS THE TOP OF PRINTER PAGE -
      IF(IPRINT.NF2O) GOTO 170
C      PRINT HEADING ON PRINTER FOR WA NUMBER/ID CODE    Be
      CALL HARDHD (ITE)                           e
      IPRINT=2
C      PRINT RECORD OF DOCUMENT ON PRINTER             .
170   CALL HARDPT(ITEM)                              A
C O    IS THIS THE BOTTOM OF PRINTER PAGEe YES SET TOP OF PAGE FLAG
190   IF(KNT/14.EC.KNI/146) IPRINT=0
      GO TO 100
C      DISPLAY THE NUMBER OF DOCUMENTS FOUND
200    WRITE (19300)
300    FORMAT(' (/)
       WRITEC1 e250 KNT WA
250   FORMAT(' THERE ARE '19'% DOCUMENTS WITH A WeAe NUMBERS,
     1 13H/1De CODE OF 94A2)
      RETURN
      END
