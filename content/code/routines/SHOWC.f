      SUBROUTINE SHOWC
C      THIS SUBROUTINE DISPLAYS ON THE USER TERMINAL THE
C       COMPLETE DOCUMENT RECORD REPRESENTATION.  THIS ROUTINE
C       CAN BE CALLED BY INPUT OR REVISE MODE TO CLARIFY THE
C       RECORD BEING USED AT HAND.  ITEMS ARE NUMBERED FOR
C       FURTHER DEFINITION OF DATA.
C
C     DATA DECLARATION AND COMMON BLOCK FOR THE MAIL LOG FILE
C
      COMMON/BLK/ MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,
     1     ADD,TWX,FSC,NRE,DDT,R,PTIT,COUNT,CON
      COMMON/SRC/ KNT,DM,DA,DDD,DTO,DL,IT,D,WA,DW,DT,DRE
     1      ,TFVD,TLVD,FVD,LVD,IEX
      COMMON/FLA/ ITRSP,IMFLE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*4 ATHR(7),TO(8),DLN(5),SUB(21),ROUT(6),PTIT(19),
     1          CON(5),TWX(6,5),FSC(6),NRE(1,3),DDT(30,21),T(21)
     1            ,TIT(24),COUNT,CONT(5),IEX(4,3)
      INTEGER*2 MS,DD(3),IDD(3),ADD(3),R,CWA(4),WA(4)
      INTEGER*2 ITRSP,IMFLE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*2 FVD(3),LVD(3),D(3),DM,DDD(3)
      INTEGER*4 DRE,DT(5),DW(5),DL(5),DA(7),IT(24),DTO(8),KNT
      DOUBLE PRECISION DTJ,TF,TL,TJUL,TFVD,TLVD,TIM,TJ
C      CLEAR USER TERMINAL SCREEN FOR OUPUT DISPLAY
      CALL CLEAR
C
C      DISPLAY RECORD
C
      WRITE(1,10)MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,ADD
10    FORMAT(2X,'1. ',A2,11X,'2. ',7A4,/,2X,'3. ',2(I2,'-'),I2,5X,'4. ',
     18A4,/,2X,'5. ',4A4,A2,/,2X,'6.  SUBJECT',/,3X,7(2A4,A2,1X),/,
     12X,'7. ',5(A3,'/'),A3,5X,'8. ',2(I2,'-'),I2,/,2X,'9. ',4A2,5X,
     1'10. ',5A4,5X,'11. ',2(I2,'-'),I2)
      WRITE(1,800)
800   FORMAT(' 12. REFERENCED DOCUMENT NUMBER(S):')
      DO 810 M=1,6
      KTW=0
       DO 820 N=1,5
       IF(TWX(M,N).NE.'    ') KTW=KTW+1
 820    CONTINUE
      IF(KTW,E920) GOTO 900
      WRITE(15850) (TWX CMoN) GNZ195)-
 850   FORMAT(5X94A49A2)
 3810  CONTINUE
 900   CONTINUE
      WRITEC1 (1000)FSC
 1000 FORMAT(' 136 %e 2A49A20'/% 5 2A4(A2)
       WRITE (101200)
 1200 FORMAT(' 14.6 ENGINFERS! 9')
       KRE=C
       DO 1400 L=143
       IFUNREC1sL) NEO?     KRE=KRE+1
C 1400 CONTINUE
       IF(KRE.EQ.0) GOTO 1050
       WRITE(1,170) CNRE(10L) 9L=193)
 170   FORMAT(5X93 CA301X))
 1050  CONTINUE
       IF(ITREP.EQ.0) COTO 1070
       WRITE(1 01100)
 1100  FORMAT(' 15. DESCRIPTION:
       DO 1500 I=1430
       KDD=0
       DO 1600 J219"21
       IF COOT(I,J) NE oT   KDD=KOD+1
 1600  CONTINUE
       IF(KDD,EN.O) GOTO 1070
      WRITE(1,180) CDOTCI oD) (J=1921)
 180   FORMAT(4X(TC1X92A499A2))
 1500  CONTINUE
 1070  CONTINUE
       RETURN
       END
