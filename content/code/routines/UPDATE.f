      SUBROUTINE UPDATE
C
C     DATA DECLARATION AND COMMON BLOCK FOR THE MAIL LOG FILE
C
      COMMON/BLK/ MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,
     1     ADD,TWX,FSC,NRE,DDT,R,PTIT,COUNT,CON
      COMMON/SRC/ KNT,DM,DA,DDD,DTO,DL,IT,D,WA,DW,DT,DRE
     1       ,TFVD,TLVD,FVD,LVD,IEX
      COMMON/FLA/ ITRSP,IMFLE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*4 ATHR(7),TO(8),DLN(5),SUB(21),ROUT(6),PTIT(19),
     1          CON(5),TWX(6,5),FSC(6),NRE(1,3),DDT(30,21),T(21)
     1         ,TIT(24),COUNT,CONT(5),IEX(4,3)
      INTEGER*2 MS,DD(3),IDD(3),ADD(3),R,CWA(4),WA(4)
      INTEGER*2 ITRSP,IMFLE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*2 FVD(3),LVD(3),D(3),DM,DDD(3)
      INTEGER*4 DRE,DT(5),DW(5),DL(5),DA(7),IT(24),DTO(8),KNT
      DOUBLE PRECISION DTJ,TF,TL,TJUL,TFVD,TLVD,TIM,TJ
C SYSCOM>KEYS.F      MNEMONIC KEYS FOR FILE SYSTEM (FTN)     31 MAY, 1977
      NOLIST
        INTEGER*2 FINISH
         INTEGER*4 DPT(19),DE(1,3),DF(6),KT
       REWIND 9
       REWIND 8
       FINISH=0
      DO 600 J=1,6
      IF(TWX(J,1).EQ.'    ') GO TO 600
100   READ(9,END=300)DA,DL,DPT,D,KT,DDD,DF,DE
      IF(FINISH.EQ.1) GO TO 200
      DO 105 K=1,5
      IF(TWX(J,K).NE.DL(K)) GOTO 200
105   CONTINUE
       FINISH=1
       DO 150 L=1,21
       IF(SUB(L).EQ.'DELA') GOTO160
150    CONTINUE
       DO 155 L=1,21
        IF(SUB(L).EQ.'APPR'.OR.SUB(L).EQ.'DISA'.OR.SUB(L).EQ.'DISP')
     1  GOTO 100
155   CONTINUE
      GO TO 200
160   WRITE(1,165)DDD
165   FORMAT(1X,'ACTION DUE DATE:',2X,2(I2,'-'),I2,/,
     1 1X,'ENTER NEW DUE DATE (IF NONE, REPEAT OLD DATE)'/)
      READ(1,170,ERR=160)DDD
170   FORMAT(3I2)
      IF(DDD(1).LE.0.OR.DDD(1).GE.13) GOTO 160
      IF(DDD(2).LE.0.OR.DDD(2).GE.32) GOTO 160
200   WRITE(8)DA,DL,DPT,D,KT,DDD,DF,DE
      GO TO 100
300   CALL SRCH$$(K$CLOS,'ACTD  ',6,0,0,0)
      CALL SRCH$$(K$CLOS,'REVS  ',6,0,0,0)
      CALL SRCH$$(K$DELE,'ACTD  ',6,0,0,0)
      CALL CNAM$$('REVS  ',6,'ACTD  ',6,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'ACTD  ',6,5,1,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'REVS  ',6,4,1,IC)
      REWIND 8
      REWIND 9
      FINISH=0
600   CONTINUE
605   READ(9,END=700) DA,DL,DPT,D,KT,DDD,DF,DE
      GO TO 605
700   RETURN
      END
