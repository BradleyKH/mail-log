      SUBROUTINE RESEA
C      THIS SUBROUTINE PERFORMS THE NASA RESPONSIBLE ENGINEER
C      SEARCH AND FORMATS THE FINDINGS FOR OUTPUT
C
C      DATA DECLARATION AND COMMON BLOCK FOR THE MAIL LOG FILE
C
      COMMON/BLK/ MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,
     1     ADD,TWX,FSC,NRE,DDT,R,PTIT,COUNT,CON
      COMMON/SRC/ KNT,DM,DA,DDD,DTO,DL,IT,D,WA,DW,DT,DRE
     1      ,TFVD,TLVD,FVD,LVD,IEX
      COMMON/FLA/ ITRSP,IMELE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*4 ATHR(7),TO(8),DLN(5),SUB(21),ROUT(6),PTIT(19),
     1          CON(5),TWX(6,5),FSC(6),NRE(1,3),DDT(30,21),T(21)
     1         ,TIT(24),COUNT,CONT(5),IEX(4,3)
      INTEGER*2 MS,DD(3),IDD(3),ADD(3),R,CWA(4),WA(4)
      INTEGER*2 ITRSP,IMELE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*2 FVD(3),LVD(3),D(3),DM,DDD(3)
      INTEGER*4 DRE,DT(5),DW(5),DL(5),DA(7),IT(24),DTO(8),KNT
      DOUBLE PRECISION DTJ,TF,TL,TJUL,TFVD,TLVD,TIM,TJ
      INTEGER*2 IPAGE,IPRINT,ITEM
C      INITIALIZE COUNTER
      KNT=0
C      INITIALIZE TOP OF PRINTER PAGE FLAG
      IPRINT=0
C      INITIALIZE FIRST FOUND FLAG
      IPAGE=0
3     WRITE(1,1)
1     FORMAT(' RESPONSIBLE ENGINEER SEARCH',/,
     1' WHO IS THE NASA RESPONSIBLE ENGINEER (INITIALS ONLY)'/)
      READ(1,2,ERR=3)DRE
2     FORMAT(A3)
C      READ DOCUMENT RECORD OF THE APPROPRIATE SUB-FILE.
100   CALL RDSUB
C      IS THE SEARCH COMPLETED ON ALL SELECTED SUB-FILES
      IF(IREAD.EQ.1) GOTO 200
      IM=IDD(1)
      ID=IDD(2)
      IY=IDD(3)
      CALL JTIME(TY,IM,ID,C,0,0,TIM)
      IF (TEVD.LE.TIM.AND.TIM.LE.TLVD) GO TO A390
      GO TO  100
890   CONTINUE
      DO 11 J=193
       IF (DRE.EQ.NRE(19D)) GO TO 150
11    CONTINUE
       GO TO 100
C       ENGINEER FOUNO
C       IS THIS THF FIRST ENGINEER FOUND
 150   IF(IPAGE.NE.0) GOTG 160
C       SET FOR FIRST ENGINEFR DISPLAY
       IPAGE=1
       ITEM=14
C       DISPLAY HEADING ON TERMINAL FOR RESPONSIBLE ENGINEER
       CALL SCRNHD(ITEM)
C        DISPLAY RECORD OF ENGINEER FOUND
 160     CALL SCRNPT(ITEM)
C       IS THIS & NEW PAGE ON THF PRINTER
       IFCIPRINT NEO? GOTO  170
C       PRINT HEADING ON PRINTER FOR RESPONSIBLE ENGINEER
       CALL HARDHD(ITEM)
       IPRINT=1
C       PRINT RECORD OF ENGINEER FOUND
 170    CALL HARDPT(ITEM)
C        IS THIS THE BOTTOM OF THE PRINTER PAGE» YES SET TOP OF PAGE FLAG
 190    IF(KNT/14.EQ.KNT/146) IPRINT=0
       GO TO 100
C      DISPLAY HOW MANY WERE FOUND
 200    WRITE(1,3090)
 300    FORMAT('' '/)
       WRITE (1 5250)KNT 9DRE
 250   FORMAT(' THERE ARE '19' DOCUMENTS WITH A RESPONSIBLE%s
      LIXe*ENGINEER OF *A7)
       RETURN
       END
