      IF(ISHT(1).LE.0) GOTO 12
      IF(ISHT(1).EQ.1.AND.ISHT(2).EQ.0) GOTO 255
      CALL SRCH$$(K$RDWR+K$NDAM,'STEMP ',6,10,1,IC)
      FINISH=0
      REWIND 12
10    READ(12,END=200)DRW,SHTN,REV,NEO,EOREF
      IF(FINISH.EQ.1) GOTO 100
      DO 20 L=1,4
      IF(IDR(L).NE.DRW(L)) GOTO 100
20    CONTINUE
      DO 25 N=1,2
      IF(ISHT(N).NE.SHTN(N)) GOTO 100
25    CONTINUE
      NEO=NEO+1
      IF(NEO.EQ.4) WRITE(1,30) (ISHT(N),N=1,2),DRW
      IF(NEO.EQ.5) WRITE(1,40) (ISHT(N),N=1,2),DRW
      IF(NEO.GE.6) WRITE(1,50) (ISHT(N),N=1,2),DRW,NEO
30    FORMAT(1X,54('*'),/,' WARNING!!! SHEET# ',I2,'.',I2,' FOR DRAWING
     1',3A4,A2,/,12X,'NOW HAS FOUR E.O.''S',/,1X,54('*'))
40    FORMAT(1X,61('*'),/,' ATTENTION!!! SHEET# ',I2,'.',I2,' FOR DRAWIN
     1G ',3A4,A2,/,' NOW HAS THE MAXIMUM ALLOWABLE OF FIVE E.O.''S',/,
     11X,61('*'))
50    FORMAT(1X,75('*'),/,' ATTENTION!!!  IMPORTANT!!!  REVISION PAST',
     1'DUE!!  IMMEDIATE ACTION REQUIRED!!',/,' SHEET#',I2,'.',I2,' FOR D
     1RAWING ',3A4,A2,' NOW HAS ',I2,' E.O.''S',/,1X,75('*'))
      DO 150 K=1,2
      EOREF(NEO,K)=EON(K)
150   CONTINUE
      IF(J.EQ.IANS) FINISH=1
100   WRITE(14) DRW,SHTN,REV,NEO,EOREF
      GO TO 10
255   CONTINUE
      CALL SRCH$$(KSROWR+KSNDAMe*°TEMP "oG,GeLYIC)
      FINISK=0
      REWIND 6
       ISHT(1)=1
       ISHT(2)=0
260   READ (6,END=285)DRAW,TIT,PTIT,DIY SYS VEH, SECT YNSHT oF REVoFNEOs
     1               FEOREF
      IF(FINISHEGQ21) GOTO 275
      DO 265 L=194
      IF (IOR(CL).NE.DRAW(L)) GOTO 275
265   CONTINUE
      FNEO=FNEO41
      IF(FNEDSEQ,4) WRITE (1930) CISHT(N) N=102)9DRAW
      IF (FNEQSEG.5) WRITE(1040) (ISHTON) PN2192)sDRAW
      IF(FNEC.GE.6) WRITE(C1950) CISHTO(N) oN=1(92)eDRAWsFNEO
      DO 270 K=152
      FEOREFCFNEOsK)=EONCK)
270   CONTINUE
      FINISH=1
275   WRITE(10) DRAW, TIT ePTIT,DT,SYS,VEH sSECT sNSHT s FREV oF NEO, FEOREF
      GO TO 260
285   CALL SRCH$$(KSCLOSs*TEMP  96909090)
      CALL SRCH$$(KSCLOSs*DRAW  *%Y969U9090)
      CALL SRCH$$(KSCELE, *ORAW  36900090)
       CALL CNAM$$(* TEMP %oSs%DRAW  %e69TC)
      CALL SRCH$$(KSROWR*KSNDAMs*DRAW %e692,1,IC)
       FINISH=0
       GO TO 250
200   CALL SRCH$$(KSCLOSs*SHEET 36000090)
      CALL SRCH$$(KECLOSo*STEMP  96509099)
      CALL SRCH$$(KSPELEs*SHFET %96909090)
      CALL CNAM$$(*STEM> *s6, "SHEET "eF IC)
      CALL SRCH$$(KSROWR*KSNDAMS*SHEET *eG,8eIGIC)
      FINISH=0
C 250 CONTINUE
300   CONTINUE
      RETURN
      END
