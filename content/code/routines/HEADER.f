      SUBROUTINE HEADER
C
C       THIS SUBROUTINE PERFORMS A PRINT OF HEADER INFORMATION TO
C        THE OUTPUT FILE TO BE SPOOLED
C
C
C     COMMON BLOCK FOR THE DRAW-EO FILE
C
      COMMON DRAW,TIT,PTIT,DT,SYS,VEH,SECT,NSHT,FREV,FNEO,FEOREF,
     1        DRW,SHTN,REV,NEO,EOREF,
     1        EON,ETIT,EPTIT,EOREV,EDT,ERDT,EOVEH,
     1        R,IDR,INEO,KNT,FIRST,SECOND,TTIT
C
C     DATA DECLARATION BLOCK FOR THE DRAW-EO FILE
C
      INTEGER*4 DRAW(4),TIT(21),PTIT(19),SYS(3),SECT(3),FEOREF(10,2),
     1           DRU(4),EOREF(10,2),EPTIT(19),ETIT(21),EON(2),
     1           IDR(4),KNT,TTIT(19)
      INTEGER*2 DT(3),VEH(2,2),NSHT,SHTN(2),FREV,FNEO,REV,NEO,
     1           EOREV,EDT(3),ERDT(3),EOVEH(2,2),R,INEO,
     1           FIRST,SECOND
C
C
      WRITE(7,200)
200   FORMAT(11X,'DRAWING TITLE',66X,'DRAWING NUMBER',10X,'DATE')
       IF(R.EQ.1) GOTO 400
      WRITE(7,300)
300   FORMAT(12X,'SHEET NUMBER',/,
     113X,'E.O. NUMBER',12X,'DATE',6X,'E.O. TITLE',/,3X,120('*'))
      GO TO 600
400   WRITE(7,500)
500   FORMAT(12X,'SHEET NUMBER',/,13X,'E.O. NUMBER',/,
     1 3X,120('*'))
600   RETURN
      END
