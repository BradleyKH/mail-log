      SUBROUTINE INPSDW
C
C     COMMON BLOCK FOR THE DRAW-EO FILE
C
      COMMON DRAW,TIT,PTIT,DT,SYS,VEH,SECT,NSHT,FREV,FNEO,FEOREF,
     1       DRW,SHTN,REV,NEO,EOREF,
     1       EON,ETIT,EPTIT,EOREV,EDT,ERDT,EOVEH,
     1       R,IDR,INEO,KNT,FIRST,SECOND,TTIT
C
C     DATA DECLARATION BLOCK FOR THE DRAW-EO FILE
C
      INTEGER*4 DRAW(4),TIT(21),PTIT(19),SYS(3),SECT(3),FEOREF(10,2),
     1          DRW(4),EOREF(10,2),EPTIT(19),ETIT(21),EON(2),
     1          IDR(4),KNT,TTIT(19)
      INTEGER*2 DT(3),VEH(2,2),NSHT,SHTN(2),FREV,FNEO,REV,NEO,
     1          EOREV,EDT(3),ERDT(3),EOVEH(2,2),R,INEO,
     1          FIRST,SECOND
C
C
C SYSCOM>KEYS.F      MNEMONIC KEYS FOR FILE SYSTEM (FTN)     31 MAY, 1977
      NOLIST
C
      INTEGER*2 IER(3),IOPT,IEOUP,NEWSHT,FINISH,ISHTN(2)
C
C     THIS ROUTINE PROVIDES THE BASIC I/O FOR THE
C       DRAWING SUBFILE INPUT/REVISE ROUTINES
C
C      INITIALIZE THE UPDATE E.O.'S ON REVISED SHEET FLAG
      IEOUP=0
      NEWSHT=0
      IF(R.EQ.0) GO TO 100
2     WRITE(1,1)
1     FORMAT(' HOW MANY ITEMS DO YOU WISH TO REVISE (MAX OF 9)',/)
      READ(1,10,ERR=2)IKNT
10    FORMAT(I3)
      IF(IKNT.LT.0) GO TO 2
      IF(IKNT.GT.9) GO TO 2
      DO 3800 LOOP=1,IKNT,1
5     WRITE(1,3)
3     FORMAT(' INPUT THE ITEM NUMBER THAT YOU WISH TO REVISE',/)
      READ(1,10,ERR=5)IR
      IF(IR.NE.8.AND.IR.NE.7) GOTO 100
      IF(IR.EQ.8) GOTO 19
9     WRITE(1,11)
11    FORMAT(' IS THIS A CORRECTION OF SHEET ITEM: ENTER YES',/,
     1' OR IS THIS A NEW SHEET ENTRY FOR A DRAWING: ENTER NEW')
      READ(1,25,ERR=9)IOPT
      IF(IOPT.EQ.'YE') GOTO 100
      IF(IOPT.NE.'NE') GOTO 9
      NEWSHT=1
      GO TO 100
19    WRITE(1,20)
20    FORMAT(' IS THIS A REVISION ENTRY FOR A NEW DRAWING SHEET',
     1 ' (YES OR NO)',/,' NOTE: A NO ANSWER INDICATES A REVISION ITEM
     1CORRECTION.',/,7X,'A YES ANSWER WILL DELETE ALL E.O.''S ',
     1'FOR THIS SHEET.')
      READ(1,25,ERR=19)IOPT
25    FORMAT(1A2)
      IF(IOPT.EQ.'NO') GOTO 100
      IF(IOPT.NE.'YE') GOTO 19
      IEOUP=1
C
C     BEGIN INPUT
C
100   IF(R.EQ.1.AND.IR.NE.1) GO TO 200
103   WRITE(1,101)
101   FORMAT(' (1) TITLE (7 WORDS - 10 CHAR.)',/'!',76X,'!'/)
110   FORMAT(1X,17A4,A2)
      LEN=10
      CALL TINPUT(TIT,LEN)
      WRITE(1,102)TIT
102   FORMAT(7(1X,2A4,A2)/)
      WRITE(1,105)PTIT
105   FORMAT(1X,19A4)
      DO 104 I=1,19
      TTIT(I)=PTIT(I)
104   CONTINUE
200   IF(R.EQ.1.AND.IR.NE.2) GO TO 400
201   WRITE(1,202)
202   FORMAT(' (2) DRAWING NUMBER',/,'!',14X,'!'/)
      READ(1,203,ERR=201)DRAW
203   FORMAT(1X,3A4,A2)
      WRITE(1,203)DRAW
400   IF(R.EQ.1.AND.IR.NE.3) GO TO 500
401   WRITE(1,402)
402   FORMAT(' (3) DRAWING DATE',/,'!MMDDYY!'/)
      READ(1,403,ERR=401)DT
403   FORMAT(1X,3I2)
      WRITE(1,403)DT
500   IF(R.EQ.1.AND.IR.NE.4) GO TO 900
501   WRITE(1,502)
502   FORMAT(' (4) SYSTEM',
     11X,'(ELEC,GSE,GUID,MECH,PROP,RF,SOP,MGS,EGS,PERF)',
     1,/,3('!',4X,'!')/)
      READ(1,503,ERR=501)SYS
503   FORMAT(1X,3(A4,2X))
      WRITE(1,503) SYS
900   IF(R.EQ.1.AND.IR.NE.5) GO TO 2200
901   WRITE(1,902)
902   FORMAT(' (5) VEHICLE',/2('!    !')/)
      READ(1,903,ERR=901)((VEH(I,J),J=1,2),I=1,2)
903   FORMAT(2(1X,I3,A1,1X))
      WRITE(1,903) ((VEH(I,J),J=1,2),I=1,2)
2200  CONTINUE
      IF(R.EQ.1.AND.IR.NE.6) GO TO 2300
2201  WRITE(1,2202)
2202  FORMAT(' (6) SECTION',/,
     15X,'E SECT  ,UPPER B   ,LOWER B     ,ALCYONE IA   ,ALCYONE IIA',/
     1,5X,'G SECT   ,UPPER C   ,LOWER C     ,ALGOL IIA    ,ALGOL IIIA',/
     1,5X,'EG SECT  ,UPPER D   ,LOWER D     ,ANTARES IIA  ,ANTARES IIIA'
     1,/,5X,'BASE A    ,UPPER F   ,LOWER F     ,ALTAIR IIIA  ,',
     1'CASTOR IIA',/,13X,'H/S 25/34    ,H/S 40/34   ,H/S 45/42',/,
     1'!',12X,'!'/)
      READ(1,2203,ERR=2201)SECT
2203   FORMAT(1X,3A4)
      WRITE(1,2203)SECT
2300   IF(R.EQ.1.AND.IR.NE.7) GOTO 2400
      IF(R.EQ.0) GOTO 2301
      IF(NEWSHT.EQ.1) CALL FIXSHT
2301  WRITE(1,2302)
2302  FORMAT(' (7) NUMBER OF SHEETS',/'!',2X,'!'/)
      READ(1,2303,ERR=2301)NSHT
2303  FORMAT(1X,I2)
      WRITE(1,2303)NSHT
      IF(R.EQ.1.AND.NEWSHT.EQ.1) CALL SHTADD
      IF(R.EQ.0) CALL INPSS
      GO TO 3800
2400  IF(R.EQ.1.AND.IR.NE.8) GO TO 2500
2407  WRITE(1,2408)
2408  FORMAT(' WHAT SHEET NUMBER IS TO BE REVISED',/,' EXAMPLE:',
     1' SHEET # 2.1   !02!!10!',/,'!   !!  !'/)
       FINISH=0
      READ(1,2409,ERR=2407) (ISHTN(K),K=1,2)
2409  FORMAT(1X,I2,2X,I2)
       IF(ISHTN(1).NE.1.OR.ISHTN(2).NE.0) GOTO 2411
2448  WRITE(1,2402)
      READ(1,2403,ERR=2448)FREV
      IF(IEOUP.EQ.0) GOTO 3800
      IF(FNEO.NE.0) FNEO=0
      DO 2449 K=1,10
      FEOREF(K,1)='    '
      FEOREF(K,2)='    '
2449  CONTINUE
      GO TO 3800
2411  CALL SRCH$$(K$RDWR+K$NDAM,'STEMP ',6,10,1,IC)
      REWIND 12
2410  READ(12,END=2470)DRW,SHTN,REV,NEO,EOREF
      IF(FINISH.EQ.1) GOTO 2460
      DO 2415 I=1,4
      IF(DRAW(I).NE.DRW(I)) GOTO 2460
2415  CONTINUE
      DO 2420 I=1,2
      IF(ISHTN(I).NE.SHTN(I)) GOTO 2460
2420  CONTINUE
2401  WRITE(1,2402)
2402  FORMAT(' SHEET REVISION: IF NONE, ENTER NC',/,'!',2X,'!'/)
      READ(1,2403,ERR=2448)REV
2403  FORMAT(1X,1A2)
      WRITE(1,2403)REV
      IF(IEOUP.EQ.0) GOTO 2455
      IF(NEO.NE.0) NEO=0
      DO 2450 K=1,10
      EOREF(K,1)='    '
      EOREF(K,2)='    '
2450  CONTINUE
2455  FINISH=1
2460  WRITE(14) DRW,SHTN,REV,NEO,EOREF
      GO TO 2410
2470  CALL SRCH$$(K$CLOS,'STEMP ',6,0,0,0)
      CALL SRCH$$(K$CLOS,'SHEET ',6,0,0,0)
      CALL SRCH$$(K$DELE,'SHEET ',6,0,0,0)
      CALL CNAM$$('STEMP ',6,'SHEET ',6,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'SHEET ',6,8,1,IC)
2500  IF(R.EQ.1.AND.IR.NE.5) GOTO 3800
      REWIND 12
2510  WRITE(1,2511)
2511  FORMAT(' WHAT SHEET NUMBER DO YOU WISH TO REVISE A REFERENCED ',
     1'E.O.',/,' EXAMPLE: SHEET # 2.1    !02!!10!',/,'!  !!  !'/)
      READ(1,2512,ERR=2510)(ISHTN(K),K=1,2)
2512  FORMAT(1X,I2,2X,I2)
      IF(ISHTN(1).NE.1.OR.ISHTN(2).NE.0) GOTO 2515
      DO 2550 I=1,10
      IF(FEOREF(I,1).NE.'    ') GOTO 2553
      GO TO 2563
2553  WRITE(1,2505) I,(FEOREF(I,J),J=1,2)
2550  CONTINUE
2563  WRITE(1,2605)
      READ(1,2620,ERR=2563) IOPT
      DO 2570 J=1,IOPT
      IF(IOPT.LT.0.OR.IOPT.GT.I) GOTO 2563
      IF(IOPT.EQ.0) GO TO 3800
2564  WRITE(1,2650) I
      READ(1,2620,ERR=2564) K
2565  WRITE(1,2660)
      READ(1,2670,ERR=2565)(FEOREF(K,N),N=1,2)
2570  CONTINUE
      GO TO 3800
2515  CALL SRCH$$(K$RDWR+K$NDAM,'STEMP ',6,10,1,IC)
2516  READ(12,END=2800)DRW,SHTN,REV,NEO,EOREF
      DO 2520 I=1,4
      IF(DRAW(I).NE.DRW(I)) GOTO 2750
2520  CONTINUE
      DO 2530 I=1,2
      IF(ISHTN(I).NE.SHTN(I)) GOTO 2750
2530  CONTINUE
      DO 2600 I=1,10
      IF(EOREF(I,1).NE.'    ') GOTO 2503
      GO TO 2603
2503  WRITE(1,2505) I,(EOREF(I,J),J=1,2)
2505  FORMAT(3X,I2,'.   ',2A4)                                            ! [?]
2600  CONTINUE
2603  WRITE(1,2605)
2605  FORMAT(' HOW MANY DO YOU WISH TO REVISE')
      READ(1,2620,ERR=2603)IOPT
2620  FORMAT(I2)
      IF(IOPT.LT.0.OR.IOPT.GT.I) GOTO 2603
      IF(IOPT.EQ.0) GOTO 2700
      DO 2700 J=1,IOPT
2640  WRITE(1,2650)I
2650  FORMAT(' ENTER THE REFERENCED E.O. NUMBER TO BE REVISED',
     1/,' NOTE: MUST BE FROM 1 TO',I2)
      READ(1,2620,ERR=2640)K
      WRITE(1,2660)
2660  FORMAT(' ENTER REVISED REFERENCED E.O.',/,'!',8X,'!'/)
      READ(1,2670,ERR=2660)(EOREF(K,N),N=1,2)
2670  FORMAT(1X,2A4)
2700  CONTINUE
2750  WRITE(14) DRW,SHTN,REV,NEO,EOREF
      GO TO 2516
2800  CALL SRCH$$(KSCLOSe*STEMP  6905090)
      CALL SRCH$$(KSCLOSs*SHEET %e6909090)
       CALL SRCH$$(KSDELEs*SHEET %96509040)
      CALL CNAM$$(*STEMP %s699SHEET ToG,IC)
      CALL SRCH$$(KSROWR*KSNOAMe*SHEET "%9698919IC)
3800  CONTINUE
C
C     END OF INPUT/REVISE ITEMS AS OF 7/26/78
C
9999  CALL SHOWDW  -
      RETURN
      END
