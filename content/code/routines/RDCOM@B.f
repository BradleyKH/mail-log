C     READ ONE LINE FROM CONSOLE OR COMMAND FILE
C
C
      SUBROUTINE RDCOM(BUF)
C
      COMMON /X/ PEDL
C
      INTEGER BUF(1),PEDL,CHAR,ANL,AKILL,AERASE
C
C     ANL, AKILL, AERASE ARE OCTAL 212, 277, 242
      DATA  ANL,AKILL,AERASE/138,191,136/
C
      PEDL=1
90    N=1
100   CALL C1IN(CHAR)
      BUF(N)=CHAR
      IF(CHAR.EQ.ANL)  RETURN
      IF(CHAR.EQ.AKILL)  GOTO 90
      IF(CHAR.EQ.AERASE)  GOTO 200
      N=N+1
      IF(N.GT.77)  GOTO999
      GOTO 100
C
200   IF(N.LE.2)  GOTO 90
      N=N-1
      GOTO 100
C
C
C     LINE LONGER THAN 77 CHAR
C
999   ILF=:212
      CALL T1OU(ILF)
      RETURN
      END
