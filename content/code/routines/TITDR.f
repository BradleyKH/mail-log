      CALL CLEAR
1001  WRITE(1,2)
2     FORMAT(' HOW MANY WORDS DO YOU WISH TO MATCH (MAX OF 4)'9/
      1/)
      READ (108, £RR=1001 ICON
8     FORMAT(I2)
