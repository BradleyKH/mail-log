      SUBROUTINE INPSC
C
C     DATA DECLARATION AND COMMON BLOCK FOR THE MAIL LOG FILE
C
      COMMON/BLK/ MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,
     1     ADD,TWX,FSC,NRE,DDT,R,PTIT,COUNT,CON
      COMMON/SRC/ KNT,DM,DA,DDD,DTO,DL,IT,D,WA,DW,DT,DRE
     1      ,TFVD,TLVD,FVD,LVD,IEX
      COMMON/FLA/ ITRSP,IMELF,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*4 ATHR(7),TO(8),DLN(5),SUB(21),ROUT(6),PTIT(19),
     1          CON(5),TWX(6,5),FSC(6),NRE(1,3),DDT(30,21),T(21)
     1         ,TIT(24),COUNT,CONT(5),IEX(4,3)
      INTEGER*2 MS,DD(3),IDD(3),ADD(3),R,CWA(4),WA(4)
      INTEGER*2 ITRSP,IMELF,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*2 FVD(3),LVD(3),D(3),DM,DDD(3)
      INTEGER*4 DRE,DT(5),DW(5),DL(5),DA(7),IT(24),DTO(8),KNT
      DOUBLE PRECISION DTJ,TF,TL,TJUL,TFVD,TLVD,TIM,TJ
      INTEGER*2 IR,I,J,II,III
      INTEGER*4 ARRAY(4),BLNK
      INTEGER*2 BUF(76),IOPT                                             ! [?]
C
C     THIS ROUTINE PROVIDES THE BASIC I/O FOR THE INPUT/REVISE ROUTINES
C
      IF(R.EQ.0) GO TO 100
2     WRITE(1,1)
1     FORMAT(' HOW MANY ITEMS DO YOU WISH TO REVISE (MAX OF 14)',/)
      READ(1,10,ERR=2)IKNT
10    FORMAT(I3)
      IF(IKNT.LT.0) GO TO 2
      IF(IKNT.GT.14) GO TO 2
      DO 9999 LP=1,IKNT,1
5     WRITE(1,3)
3     FORMAT(' INPUT THE ITEM NUMBER THAT YOU WISH TO REVISE',/)
      READ(1,10,ERR=5)IR
      CALL CKIR(IR,I)
      IF(I.GT.0) GO TO 100
      GO TO 5
C
C     BEGIN INPUT
C
100   IF(R.EQ.1.AND.IR.NE.1) GO TO 200
103   WRITE(1,101)
101   FORMAT(
     1' (1) MAIL STATUS - (VC) VOUGHT CORRESPONDENCE',/,
     1'                   (IM) INCOMING MAIL',/,
     1'                   (OM) OUTGOING MAIL',/
     1'!  !',/)
      READ(1,104,ERR=103)MS
      IF(MS.EQ.'VC') GO TO 105
      IF(MS.EQ.'IM') GO TO 105
      IF(MS.EQ.'OM') GO TO 105
      WRITE(1,106)MS
106   FORMAT('GGTHE MAIL STATUS CODE YOU HAVE ENTERED ('A2,
     1') IS NOT VALID - TRY AGAIN'/)
      GO TO 103
104   FORMAT(1X,A2)
105   WRITE(1,104)MS
200   IF(R.EQ.1.AND.IR.NE.2) GO TO 300
201   WRITE(1,202)
202   FORMAT(' (2) AUTHOR/SOURCE',/
     1'!',28X,'!'/)
      READ(1,203,ERR=201)ATHR
      WRITE(1,203)ATHR
203   FORMAT(1X,7A4)
300   IF(R.EQ.1.AND.IR.NE.3) GO TO 400
301   WRITE(1,302)
302   FORMAT(' (3) DOCUMENT DATE ',/,'!MMDDYY!'/)
      READ(1,303,ERR=301)DD
303   FORMAT(1X,3I2)
      IF(DD(1).GT.12) GO TO 301
      IF(DD(2).GT.31) GO TO 301
      WRITE(1,303)DD
400   IF(R.EQ.1.AND.IR.NE.4) GO TO 500
401   WRITE(1,402)
402   FORMAT(' (4) TO ',/,'!'32X,'!'/)
      READ(1,403,ERR=401)TO
403   FORMAT(1X,8A4)
      WRITE(1,403)TO
500   IF(R.EQ.1.AND.IR.NE.5) GO TO 600
501   WRITE(1,502)
502   FORMAT(' (5) DOCUMENT/LETTER NUMBER',/,'!',18X,'!'/)
      READ(1,503,ERR=501)DLN
503   FORMAT(1X,4A4,A2)
      WRITE(1,503) DLN
600   IF(R.EQ.1.AND.IR.NE.6) GO TO 700
601   WRITE(1,602)
602   FORMAT(' (6) SUBJECT (7 WORDS - 10 CHAR/WORD)',/
     1'!',76X,'!'/)
      LEN=10
       CALL TINPUT(TIT,LEN)
      DO 610 IJ=1,21
610   SUB(IJ)=TIT(IJ)
      WRITE(1,603)SUB
603   FORMAT(7(1X,2A4,A2))
700   IF(R.EQ.1.AND.IR.NE.7) GO TO 800
701   WRITE(1,702)
702   FORMAT(' (7) ROUTING',/,6('!   !')/)
      READ(1,703,ERR=701)ROUT
703   FORMAT(6(1X,A3,1X))
      WRITE(1,703) ROUT
800   IF(R.EQ.1.AND.IR.NE.8) GO TO 900
801   WRITE(1,802)
802   FORMAT(' (8) INPUT DATA DATE',/,'!MMDDYY!',/)
       IF(R.EQ.0) GOTO 805
      READ(1,803,ERR=801)IDD
803   FORMAT(1X,3I2)
      GO TO 810
805   REWIND 10
      READ(10,803)IM,ID,IY
      IDD(1)=IM
      IDD(2)=ID
      IDD(3)=IY
      REWIND 10
810   WRITE(1,803) IDD
900   IF(R.EQ.1.AND.IR.NE.9) GO TO 950
901   WRITE(1,902)
902   FORMAT(' (9)  W.A. NUMBER / ID. CODE',/,
     1'!',8X,'!'/)
      READ(1,903,ERR=901)CWA
903   FORMAT(1X,4A2)
      WRITE(1,903)CWA
        CALL GETCON
      IF(CON(1).NE.'    ') GOTO 1001
909   WRITE(1,910)
910   FORMAT(' IS THERE A CONTRACT NUMBER FOR THIS DOCUMENT (YES OR NO)'
     1 )
      READ(1,2300,ERR=909) IOPT
      IF(IOPT.EQ.'YE') GOTO 951
      IF(IOPT.NE.'NO') GOTO 909
      GO TO 1050
950   IF(R.EQ.1.AND.IR.NE.10) GOTO 1100
951   WRITE(1,952)
952   FORMAT(' (10) CONTRACT NUMBER',/,'!',20X,'!'/)
      READ(1,953,ERR=951) CONT
953   FORMAT(1X,5A4)
      WRITE(1,953)CONT
      GO TO 1100
1001  WRITE(1,1002)CON
1002  FORMAT(' CONTRACT NUMBER  ',5A4)
1050   DO 1060 I=1,5
        CONT(I)=CON(I)
1060   CONTINUE
1100  IF(R.EQ.1.AND.IR.NE.11) GO TO 1200
1101  WRITE(1,1102)
1102  FORMAT(' (11) ACTION ITEM DUE DATE',/,'!MMDDYY!'/)
      READ(1,1103,ERR=1101)ADD
      IF(ADD(1).GT.12) GO TO 1101
      IF(ADD(2).GT.31) GO TO 1101
      WRITE(1,1103)ADD
1103  FORMAT(1X,3I2)
1200  IF(R.EQ.1.AND.IR.NE.12) GO TO 1300
1202  WRITE(1,1204)
      ARRAY(4)=BLNK
      CALL GETWRD(BUF,ARRAY,LEN)
      TIT(I)=ARRAY(1)
      TIT(I+1)=ARRAY(2)
      TIT(I+2)=ARRAY(3)
      TIT(I+3)=ARRAY(4)
      I=I+2
1531  CONTINUE
      WRITE(1,1506)(TIT(I),I=1,21)
1506  FORMAT(7(1X,2A4,A2))
      I18=21
      DO 1507 J=1,I18
      DDT(IJ,J)='    '
      DDT(IJ,J)=TIT(J)
      TIT(J)='    '
1507  CONTINUE
1504  CONTINUE
2200  CONTINUE
      R=1                                                                ! [?]
      IR=0
9999  CONTINUE
      CALL SHOWC
2302  WRITE(1,2303)
2303  FORMAT(/,1H0,/,' CHECK RECORD FOR ERRORS: IF CORRECT, ENTER COR',
     1/,26X,'IF REVISION NEEDED, ENTER REV'/)
      READ(1,2300)IOPT
2300  FORMAT(1A2)
      IF(IOPT.EQ.'RE') GOTO 2
      IF(IOPT.NE.'CO') GOTO 2302
C
C     END OF INPUT REVISE ITEMS AS OF 8/26/78
C
      RETURN
      END
