      SUBROUTINE GETCON
C
C     DATA DECLARATION AND COMMON BLOCK FOR THE MAIL LOG FILE
C
      COMMON/BLK/ MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,
     1     ADD,TWX,FSC,NRE,DDT,R,PTIT,COUNT,CON
      COMMON/SRC/ KNT,DM,DA,DDD,DTO,DL,IT,D,WA,DW,DT,DRE
     1      ,TFVD,TLVD,FVD,LVD,IFX
      COMMON/FLA/ ITRSP,IMELE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*4 ATHR(7),TO(6),DLN(5),SUB(21),ROUT(6),PTIT(19),
     1          CON(5),TWX(6,5),FSC(6),NRE(1,3),DDT(30,21),T(21)
     1         ,TIT(24),COUNT,CONT(5),IEX(4,3)
      INTEGER*2 MS,DD(3),IDD(3),ADD(3),R,CWA(4),WA(4)
      INTEGER*2 ITRSP,IMELE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*2 FVD(3),LVD(2),D(3),DM,DDD(3)
      INTEGER*4 DRE,D1(5),DW(5),DL(5),DA(7),IT(24),DTO(8),KNT
      DOUBLE PRECISION DTJ,TF,TL,TJUL,TFVD,TLVD,TIM,TJ
C SYSCOM>KEYS.F      MNEMONIC KEYS FOR FILE SYSTEM (FTN)     31 MAY, 1977
      NOLIST
      CALL SRCH$$(K$RDWR+K$NDAM,'CTAB  ',6,16,1,IC)
      REWIND 20
650    READ(20,655,END=690)WA,CON
655    FORMAT(5X,4A2,2X,5A4)
      IF(CWA(1).EQ.'  ') GOTO 680
      IF(CWA(1).EQ.'33'.AND.CWA(2).EQ.'02') GOTO 670
      IF(CWA(1).EQ.'38'.AND.CWA(2).EQ.'04'.OR.CWA(2).EQ.'09') GOTO 660
      IF(CWA(1).NE.WA(1)) GOTO 650
      IF(CWA(2).NE.WA(2)) GOTO 650
      GO TO 800
660    DO 665 I=1,4
      IF(CWA(I).NE.WA(I)) GOTO 650
665    CONTINUE
      GO TO 800
670    IF(CWA(1).NE.WA(1)) GOTO 650
      IF(CWA(2).NE.WA(2)) GOTO 650
      IF(CWA(3).NE.'AB'.AND.CWA(3).NE.'BA') GO TO 800
      IF(CWA(3).EQ.'AB'.AND.WA(3).EQ.'A ') GOTO 800
      IF(CWA(3).EQ.'BA'.AND.WA(3).EQ.'B ') GOTO 800
      GO TO 650                                            I
680   DO 685 J=105
      CON(U) =?
685   CONTINUE
       GO TO 800
690   CON(1)=°UA NO
      CON(2)="0T FP
      CON(3)="0UND®
      CON(4)=* SEE?
      CON(5)=" RUK*
300     REWIND 20
      CALL SRCH$$(KSCLOS, CTAB   ® 96005090)
        KLTURN
      END
