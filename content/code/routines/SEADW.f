      SUBROUTINE SEADW
C
C     COMMON BLOCK FOR THE DRAW-EO FILE
C
      COMMON DRAW,TIT,PTIT,DT,SYS,VEH,SECT,NSHT,FREV,FNEO,FEOREF,
     1        DRW,SHTN,REV,NEO,EOREF,
     1        EON,ETIT,EPTIT,EOREV,EDT,ERDT,EOVEH,
     1        R,IDR,INEO,KNT,FIRST,SECOND,TTIT
C
C     DATA DECLARATION BLOCK FOR THE DRAW-EO FILE
C
      INTEGER*4 DRAW(4),TIT(21),PTIT(19),SYS(3),SECT(3),FEOREF(10,2),
     1          DRW(4),EOREF(10,2),EPTIT(19),ETIT(21),EON(2),
     1          IDR(4),KNT,TTIT(19)
      INTEGER*2 DT(3),VEH(2,2),NSHT,SHTN(2),FREV,FNEO,REV,NEO,
     1           EOREV,EDT(3),ERDT(3),EOVEH(2,2),R,INEO,
     1           FIRST,SECOND
C
C
C SYSCOM>KEYS.F       MNEMONIC KEYS FOR FILE SYSTEM (FTN)      31 MAY, 1977
      NOLIST
      INTEGER*2 IDES,IOPT
C
C     THIS IS THE SEARCH DRIVER ROUTINE FOR THE DRAW FILE
C
      J=401
        R=0
      CALL SRCH$$(K$RDWR+K$NSAM,'OUT   ',6,3,0,0)
      WRITE(7,9999)J
9999  FORMAT(1A2)
      WRITE(1,1)
1     FORMAT(' YOU ARE NOW VALIDATED TO SEARCH DATA IN THE ',/
     1' DRAWING FILE - THE FOLLOWING SEARCH MODES ',/'
     1' ARE AVAILABLE FOR YOUR USE - ',/
     1'MODE                   KEY',/
     2'TITLE                  TITLE',/
     3'DRAWING NUMBER         DRAW',/
     4'DRAWING DATE           DATE',/
     5'SYSTEM                 SYS',/
     1'VEHICLE                VEH',/
     1'SECTION                SECT',/
     1'VENDOR CODE            CODE',/
     1'ALL                    ALL',/
     1'REV ACTION DUE         ACT',/
     1'E.O. NUMBER            EO',/
     1'QUIT                   QUIT',/
     1'  PLEASE SELECT THE DESIRED MODE',//)
      REWIND 6
6     READ(1,3)IDES
3     FORMAT(1A2)
      IF(IDES.EQ.'QU') GOTO 10
100   WRITE(1,110)
110   FORMAT(1X,'DO YOU DESIRE THE OPTIONAL BRIEF OUTPUT',/,
     1'   RECOMMENDED FOR ALL AND ACTION DUE SEARCHES',/,
     1' (YES OR NO)'/)
      READ(1,3)IOPT
      IF(IOPT.EQ.'NO') GOTO 111
      IF(IOPT.NE.'YE') GOTO 100
      R=1
111   IF(IDES.EQ.'TI') CALL TITDW
      IF(IDES.EQ.'AL') CALL ALDW
      IF(IDES.EQ.'AC') CALL ACTDUE
      IF(IDES.EQ.'DR') CALL DRAWN
      IF(IDES.EQ.'DA') CALL DATOW
      IF(IDES.EQ.'SY') CALL SYSDW
      IF(IDES.EQ.'VE') CALL VEHND
      IF(IDES.EQ.'SE') CALL SECTN
      IF(IDES.EQ.'CO') CALL CODE
      IF(IDES.EQ.'EO') CALL EONN
99    WRITE(1,98)
98     FORMAT(' TO CONTINUE, DEPRESS THE RETURN KEY'/)
      READ(1,9999)IDES
      IF(IDES.NE.'  ') GOTO 99
      CALL CLEAR
      WRITE(1,1)
      REWIND 6
        REWIND 12
        REWIND 18
      GO TO 6
10    WRITE(1,11)
11    FORMAT(' DO YOU WANT A HARD COPY OF THE INFORMATION FOUND',/,
     1' (YES OR NO)')
      READ(1,3) IDES
      IF(IDES.EQ.'YE') GO TO 20
      IF(IDES.EQ.'NO') GO TO 15
      GO TO 10
15    CALL SRCH$$(K$CLOS,'OUT   ',6,0,0,0)
      CALL SRCH$$(K$DELE,'OUT   ',6,0,0,0)
      RETURN
20    CALL SRCH$$(K$CLOS,'OUT   ',6,0,0,0)
      CALL SRCH$$(K$CLOS,'DRAW  ',6,0,0,0)
      CALL SRCH$$(K$CLOS,'EO    ',6,0,0,0)
      CALL SRCH$$(K$CLOS,'SHEET ',6,0,0,0)
      CALL COMI$$('SOUT',4,12,IC)
      CALL EXIT
      END
