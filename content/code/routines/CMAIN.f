      SUBROUTINE CMAIN
C
C     COMMON BLOCK FOR THE DIR FILE
C
      COMMON TIT,PTIT,DIR,RPT,DT,SYS,WAN,CON,ID,VEH,ACT,R
      COMMON COMP,REV,RDAT,WA
C
C
C     DATA DECLARATION BLOCK FOR THE DIR FILE
C
      INTEGER*4 TIT(21),PTIT(19),DIR(4),RPT(4),SYS(3),CON(5),ID,ACT
      INTEGER*4 COMP(21)
      INTEGER*2 DT(3),WAN(4),VEH(2,2),R,REV,RDAT(3),WA(4)
C
C
C
C     THIS IS THE BASIC OUTPUT ROUTINE FOR THE SPOOLER AND TERMINAL
C
      WRITE(1,998)
998   FORMAT(//)
999   FORMAT(1H0)
      WRITE(7,999)
103   WRITE(1,101)
      WRITE(7,101)
101   FORMAT(' (1) TITLE '/)
      WRITE(1,102)PTIT
      WRITE(7,102)PTIT
102   FORMAT(1X,19A4)
      IF(REV.NE.'  ') GOTO 201
      WRITE(1,150)DIR,REV
      WRITE(7,150)DIR,REV
150   FORMAT(' (2) DIR/REPORT NUMBER  (8) REVISION',/,1X,3A4,A2,9X,1A2/)
      GO TO 400
201   WRITE(1,202)DIR,REV
202   FORMAT(' (2) DIR/REPORT NUMBER  (8) REVISION',/,1X,3A4,A2,9X,
     1 'REV ',1A2/)
      WRITE(7,202)DIR,REV
400   WRITE(7,402)DT,RDAT
      WRITE(1,402)DT,RDAT
402   FORMAT(' (3) DOCUMENT DATE',6X,'(9) REVISION DATE',/,1X,2(I2,'-'),
     1 I2,15X,2(I2,'-'),I2/)
501   WRITE(1,502)SYS
      WRITE(7,502)SYS
502   FORMAT(' (4) SYSTEM',/,3(1X,A4)/)
601   WRITE(1,602)WAN
      WRITE(7,602)WAN
602   FORMAT(' (5) W.A. NUMBER/ID CODE',/,1X,4A2/)
701   WRITE(1,702)CON
      WRITE(7,702)CON
702   FORMAT(' (6) CONTRACT NUMBER',/,1X,5A4/)
901   WRITE(1,902)((VEH(I,J),J=1,2),I=1,2)
      WRITE(7,902)((VEH(I,J),J=1,2),I=1,2)
902   FORMAT(' (7) VEHICLE',/,1X,I3,A1,1X,I3,A1/)
      CALL RECYCL
      CALL PAUS
      RETURN
      END
