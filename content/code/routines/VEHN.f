      SUBROUTINE VEHN
C
C     COMMON BLOCK FOR THE DIR FILE
C
      COMMON TIT,PTIT,DIR,RPT,DT,SYS,WAN,CON,ID,VEH,ACT,R
      COMMON COMP,REV,RDAT,WA
C
C
C     DATA DECLARATION BLOCK FOR THE DIR FILE
C
      INTEGER*4 TIT(21),PTIT(19),DIR(4),RPT(4),SYS(3),CON(5),ID,ACT
      INTEGER*4 COMP(21)
      INTEGER*2 DT(3),WAN(4),VEH(2,2),R,REV,RDAT(3),WA(4)
C
C
C
C     THIS ROUTINE LOCATED ALL ENTRIES IN THE DIR/REPORT FILE
C     WHICH ARE RELATED TO EITHER A SPECIFIC VEHICLE OR VEHICLE
C
      INTEGER*2 VEH1(2),VS(4),VKNT
      VKNT=0
      CALL CLEAR
1     WRITE(1,2)
2     FORMAT('WHAT IS THE DESIRED VEHICLE NUMBER')
      READ(1,3,ERR=1)VEH1
3     FORMAT(2(I3,A1))
999   WRITE(1,100)
100   FORMAT('WHAT IS THE FIRST VALID VEHICLE NUMBER',/)
      READ(1,101,ERR=100)(VS(I),I=1,2)
998   WRITE(1,102)
102   FORMAT('WHAT IS THE LAST VALID VEHICLE NUMBER',/,
     1'NOTE  -  THE DEFALT IS VEHICLE 999')
      READ(1,101,ERR=998)(VS(I),I=3,4)
101   FORMAT(I3,A1,2X,I3,A1)
      IF(VEH1(1).LT.VS(1)) GO TO 999
      IF(VS(3).EQ.0) VS(3)=999
      IF(VS(3).LT.VEH1(1)) GO TO 998
4     READ(6,END=202)TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
C     TF CVEH (191) eLT2VSC1)0) GO TO 4            z
      IF(VEHC2(1) -GToVS(3)) GO TO 4
      IF (VEH( 192) -NE, TS.AND.VEH( 191).EQ.VEHI(1)) GO TO 1001
      IF (VEH (192).EQ. SP.AND.VEH( 191) -LE,VEHI(1)) GO TO 1001
      GOTO 4
1001  VKNT=VKNT+1
      CALL FMAIN
      GO TO 4
202   WRITE(1,201) VKNT,VEH1
C 201° FORMATC*THERE ARE *110* DIR/REPORTS RELATING*s/y
      1°TO VEHICLE *139A1/)
      RETURN
      END
