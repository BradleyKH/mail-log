      SUBROUTINE SHTADD
C
C     COMMON BLOCK FOR THE DRAW-EO FILE
C
      COMMON DRAW,TIT,PTIT,DT,SYS,VEH,SECT,NSHT,FREV,FNEO,FEOREF,
     1       DRW,SHTN,REV,NEO,EOREF,
     1       EON,ETIT,EPTIT,EOREV,EDT,ERDT,EOVEH,
     1       R,IDR,INEO,KNT,FIRST,SECOND,TTIT
C
C     DATA DECLARATION BLOCK FOR THE DRAW-EO FILE
C
      INTEGER*4 DRAW(4),TIT(21),PTIT(19),SYS(3),SECT(3),FEOREF(10,2),
     1          DRW(4),EOREF(10,2),EPTIT(19),ETIT(21),EON(2),
     1          IDR(4),KNT,TTIT(19)
      INTEGER*2 DT(3),VEH(2,2),NSHT,SHTN(2),FREV,FNEO,REV,NEO,
     1          EOREV,EDT(3),ERDT(3),EOVEH(2,2),R,INEO,
     1          FIRST,SECOND
C
C
C SYSCOM>KEYS.F      MNEMONIC KEYS FOR FILE SYSTEM (FTN)     31 MAY, 1977
      NOLIST
      INTEGER*2 IIREV,IISHTN(2),IINEO,FINISH
      INTEGER*4 IIEORE(10,2)
      FINISH=0
5     WRITE(1,10)
10    FORMAT(' ENTER SHEET NUMBER:  EXAMPLE SHEET#2.1   !02!!10!',/,
     1'!  !!  !'/)
      READ(1,15,ERR=5)(IISHTN(N),N=1,2)
15    FORMAT(1X,I2,2X,I2)
      IF(IISHTN(1).EQ.1) GOTO 30
16    IF(IISHTN(1).EQ.SHTN(1)) GOTO 105
      DO 20 I=1,4
      IF(DRW(I).NE.DRAW(I)) GOTO 30
20    CONTINUE
      GO TO 105
30    IIREV='NC'
      IINEO=0
      WRITE(14)DRW,IISHTN,IIREV,IINEO,IIEORE
      WRITE(14)DRW,SHTN,REV,NEO,EOREF
      FINISH=1
100   READ(12,END=200)DRW,SHTN,REV,NEO,EOREF
      IF(FINISH.EQ.0) GOTO 16
105   WRITE(14)DRW,SHTN,REV,NEO,EOREF
      GO TO 100
200   CALL SRCH$$(K$CLOS,'SHEET ',6,0,0,0)
      CALL SRCH$$(K$CLOS,'STEMP ',6,0,0,0)
      CALL SRCH$$(K$DELE,'SHEET ',6,0,0,0)
      CALL CNAM$$('STEMP ',6,'SHEET ',6,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'SHEET ',6,8,1,IC)
      RETURN
      END
