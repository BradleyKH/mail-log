      SUBROUTINE SCRNHD(ITEM)
C      THIS SUBROUTINE PERFORMS THE DISPLAY ON USER TERMINAL OF
C       THE APPROPRIATE HEADER FOR MAIL LOG SEARCHES
C
C     DATA DECLARATION AND COMMON BLOCK FOR THE MAIL LOG FILE
C
      COMMON/BLK/ MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,
     1     ADD,TWX,FSC,NRE,DDT,R,PTIT,COUNT,CON
      COMMON/SRC/ KNT,DM,DA,DDD,DTO,DL,IT,D,WA,DW,DT,DRE
     1      ,TFVD,TLVD,FVD,LVD,IEX
      COMMON/FLA/ ITRSP,IMFLE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*4 ATHR(7),TO(8),DLN(5),SUB(21),ROUT(6),PTIT(19),
     1          CON(5),TWX(6,5),FSC(6),NRE(1,3),DDT(30,21),T(21)
     1         ,TIT(24),COUNT,CONT(5),IEX(4,3)
      INTEGER*2 MS,DD(3),IDD(3),ADD(3),R,CWA(4),WA(4)
      INTEGER*2 ITRSP,IMFLE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*2 FVD(3),LVD(3),D(3),DM,DDD(3)
      INTEGER*4 DRE,DT(5),DW(5),DL(5),DA(7),IT(24),DTO(8),KNT
      DOUBLE PRECISION DTJ,TF,TL,TJUL,TFVD,TLVD,TIM,TJ
      INTEGER*2 ITEM
C      CLEAR SCREEN FOR DISPLAY
      CALL CLEAR
      WRITE(1,10)
 10   FORMAT(2X,78('*'))
C      DETERMINE THE ITEM OF SEARCH FOR SPECIFIC HEADER
      IF(ITEM.EQ.1) WRITE(1,20)DM
      IF(ITEM.EQ.2) WRITE(1,30)DA
      IF(ITEM.EQ.3) WRITE(1,40)DDD
      IF(ITEM.EQ.4) WRITE(1,45)DTO
      IF(ITEM.EQ.5) WRITE(1,50)DL
      IF(ITEM.EQ.6) WRITE(1,60)((IEX(I,J),J=1,3),I=1,4)
      IF(ITEM.EQ.8) WRITE(1,70)D
      IF(ITEM.EQ.9) WRITE(1,80)WA
      IF(ITEM.EQ.10) WRITE(1,90)DW
      IF(ITEM.EQ.11) WRITE(1,100)
      IF(ITEM.EQ.14) WRITE(1,120)DRE
        IF(ITEM.EQ.50) WRITE(1,15)
C      DISPLAY ITEM NAME AND ENTRY TO MATCH
 15    FORMAT(2X,'*',38X,'PRINT ALL',29X,'*')
 20   FORMAT(2X,'*',32X,'MAIL STATUS:  ',A2,28X,'*')
 30   FORMAT(2X,'*',15X,'AUTHOR/SOURCE:  ',7A4,17X,'*')
 40   FORMAT(2X,'*',30X,'DOCUMENT DATE:  ',2(I2,'-'),I2,22X,'*')
 45   FORMAT(2X,'*',20X,'WHO TO:  ',8A4,15X,'*')
 50   FORMAT(2X,'*',20X,'DOCUMENT/LETTER NUMBER:  ',4A4,A2,13X,'*')
 60   FORMAT(2X,'*',20X,'SUBJECT:  ',4(2A4,A2,1X),2X,'*')
 70   FORMAT(2X,'*',30X,'INPUT DATE:  ',2(I2,'-'),I2,25X,'*')
 80   FORMAT(2X,'*',25X,'W.A. NUMBER/ID CODE:  ',4A2,21X,'*')
 90   FORMAT(2X,'*',25X,'CONTRACT NUMBER:  ',5A4,13X,'*')
100   FORMAT(2X,'*',32X,'ACTION DUE DATE',29X,'*')
120   FORMAT(2X,'*',22X,'NASA RESPONSIBLE ENGINEER:  ',A3,23X,'*')
C      DISPLAY THE DISPLAY FORMAT LINE ONE
      WRITE(1,125)
125   FORMAT(2X,'* SUBJECT',68X,'*')
C      DISPLAY THE DISPLAY FORMAT LINE TWO
      WRITE(1,130)
130   FORMAT(2X,'* TYPE/LETTER NUMBER',5X,'FILE SYSTEM CODE',8X,
     1 'INPUT DATE-CODE',13X,'*')
       IF(ITEM.EQ.11) WRITE(1,600)
600   FORMAT(2X,'* AUTHOR / SOURCE',8X,'RESPONSIBLE ENGINEER',4X,        ! [?]
     1'DUE DATE',20X,'*')
       IF(ITEM.EQ.11.OR.ITEM.EQ.50) GOTO 650
       WRITE(1,625)
625    FORMAT(2X'* REFERENCED DOCUMENTS',55X,'*')
650   WRITE(1,10)
      RETURN
      END
