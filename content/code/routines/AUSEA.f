      SUBROUTINE AUSEA
C      THIS SUBROUTINE PERFORMS THE AUTHOR SEARCH FOR MAIL LOG
C
C     DATA DECLARATION AND COMMON BLOCK FOR THE MAIL LOG FILE
C
      COMMON/BLK/ MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,
     1     ADD,TWX,FSC,NRE,DDT,R,PTIT,COUNT,CON
      COMMON/SRC/ KNT,DM,DA,DDD,DTO,DL,IT,D,WA,DW,DT,DRE
     1      ,TFVD,TLVD,FVD,LVD,IEX
      COMMON/FLA/ ITRSP,IMFLE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*4 ATHR(7),TO(8),DLN(5),SUB(21),ROUT(6),PTIT(19),
     1          CON(5),TWX(6,5),FSC(6),NRE(1,3),DDT(30,21),T(21)
     1          ,TIT(24),COUNT,CONT(5),IEX(4,3)
      INTEGER*2 MS,DD(3),IDD(3),ADD(3),R,CWA(4),WA(4)
      INTEGER*2 ITRSP,IMFLE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*2 FVD(3),LVD(3),D(3),DM,DDD(3)
      INTEGER*4 DRE,DT(5),DW(5),DL(5),DA(7),IT(24),DTO(8),KNT
      DOUBLE PRECISION DTJ,TF,TL,TJUL,TFVD,TLVD,TIM,TJ
      INTEGER*2 IPAGE,IPRINT
C      INITIALIZE THE FOUND COUNTER
      KNT=0
C      INITIALIZE THE FIRST FOUND FLAG
      IPAGE=0
C      INITIALIZE THE TOP OF PRINTER PAGE FLAG
       IPRINT=0
3     WRITE(1,1)
1     FORMAT(' THIS IS THE DOCUMENT AUTHOR/SOURCE SEARCH',/,
     1' WHAT IS THE DESIRED AUTHOR/SOURCE',/)
      READ(1,2,ERR=3)DA
2     FORMAT(7A4)
      WRITE(1,2)DA
C      READ DOCUMENT RECORD OF THE APPROPRIATE SUB-FILE
100   CALL RDSUB
C      IS THE SEARCH COMPLETED ON ALL SELECTED SUB-FILES
       IF(IREAD.EQ.1) GOTO 200
      IM=IDD(1)
      ID=IDD(2)
      IY=IDD(3)
      CALL JTIME(TY,IM, ID O,0,0,TIM)
      IF(TEVD.LE.TIM.AND.TIM.LE.TLVD)GO TO 890
      GO TO 100
890   CONTINUE
      DO 101 I=1497
      IF (ATHR(T).NE.DA(I)) GO TO 100
101   CONTINUE
C      AN AUTHOR WAS FOUND AND MATCHFD
C      IS THIS THE FIPST DOCUMENT FOUND WITH THE AUTHOR
150   IF(IPAGE.NE.0) GOTO 160
C       SET UP FOR DISPLAY OF DOCUMENT
      ITEM=2
      IPAGE=1
C       DISPLAY HEADING ON TERMINAL FOR AUTHOR
      CALL SCRNHD(ITEM)
C      CISPLAY RECORD OR DOCUMENT FOUND WITH AUTHOR
160   CALL SCRNPT(ITEM)
C      IS THIS A NEW PAGE ON PRINTER
      IF(IPRINT.NE.20) GOTO 170
C      PRINT HEADING ON PRINTER FOR AUTHOR SEARCH.
      CALL HARDHD(ITEN)
      IPRINT=1
C      FRINT RECORD OF DOCUMFNT FOUND FOR AUTHOR
170   CALL HARDPT(ITEM)
C      IS THIS THE BOTTOM OF PRINTER PAGEs YES SET TOP OF PAGE FLAG
190    IF(KNT/14.EQ.KNT/14.) IPRINT=0
      GO TO 100
C      DISPLAY THF NUMBER OF DOCUMENTS FOUND
200    WRITE(1,300)
300    FORMAT(' '&/)
      WRITE(1,250) KNT,DA
250   FORMAT(' THERE ARE'I5' DOCUMENTS WITH A AUTHOR/SOURCE OF %e/'
     1 7A4)
      RETURN
      END
