       SUBROUTINE WHERE
C      THIS SUBROUTINE PERFORMS THE FUNCTION OF DETERMINING
C       WHICH SUB-FILES ARE TO BE OPENED FOR USE.
C
C     DATA DECLARATION AND COMMON BLOCK FOR THE MAIL LOG FILE
C
      COMMON/BLK/ MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,
     1     ADD,TWX,FSC,NRE,DDT,R,PTIT,COUNT,CON
      COMMON/SRC/ KNT,DM,DA,DDD,DTO,DL,IT,D,WA,DW,DT,DRE
     1      ,TFVD,TLVD,FVD,LVD,IEX
      COMMON/FLA/ ITRSP,IMELE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*4 ATHR(7),TO(8),DLN(5),SUB(21),ROUT(6),PTIT(19),
     1          CON(5),TWX(6,5),FSC(6),NRE(1,3),DDT(30,21),T(21)
     1         ,TIT(24),COUNT,CONT(5),IEX(4,3)
      INTEGER*2 MS,DD(3),IDD(3),ADD(3),R,CWA(4),WA(4)
      INTEGER*2 ITRSP,IMELE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*2 FVD(3),LVD(3),D(3),DM,DDD(3)
      INTEGER*4 DRE,DT(5),DW(5),DL(5),DA(7),IT(24),DTO(8),KNT
      DOUBLE PRECISION DTJ,TF,TL,TJUL,TFVD,TLVD,TIM,TJ
C SYSCOM>KEYS.F     MNEMONIC KEYS FOR FILE SYSTEM (FTN)     31 MAY, 1977
      NOLIST
      INTEGER*2 IOPT,IFILE
C
C      INITIALIZE ALL SUB-FILE FLAGS:
C                  ITRSP REPRESENTS THE TRANSMITTAL/SPECIFICATION SUB-FILE
C                  IMELE REPRESENTS THE MEMO/LETTER SUB-FILE
C                  ITWFX REPRESENTS THE TWX/MAGNAFAX/RAPIFAX SUB-FILE
C                  IANN  REPRESENTS THE ANNOUNCEMENT SUB-FILE
C                  IPR   REPRESENTS THE PURCHASE REQUEST SUB-FILE
C                  IMIS  REPRESENTS THE MISCELLANEOUS/REPORT SUB-FILE
C
      ITRSP=0
      IMELE=0
      ITWFX=0
      IANN =0
      IPR  =0
      IMIS =0
10    WRITE(1,100)
100   FORMAT(2X,'SUB FILE SELECTION:',/,2X,'1.  TRANSMITTAL/SPECIFICATIO
     1N SUB-FILE',/,2X,'2.  MEMO/LETTER SUB-FILE',/,2X,
     1'3.  TWX/MAGNAFAX/RAPIFAX SUB-FILE',/,2X,'4.  ANNOUNCEMENT SUB-FIL
     1E',/,2X,'5.  PURCHASE REQUEST SUB-FILE',/,2X,'6.  MISCELLANEOUS/',
     1'REPORT SUB-FILE',/,2X,36('*'),/,2X,
     1'HOW MANY SUBFILES DO WISH TO OPEN'/)
C
C      PERFORM VALIDITY CHECK ON USER ENTRY
C
      READ(1,110,ERR=10)IFILE
110   FORMAT(I2)
      IF(IFILE.LE.0.OR.IFILE.GT.6) GOTO 10
      IF(IFILE.EQ. 6) GOTO 300
      DO 200 I=1,6
115   WRITE(1,120) I
120   FORMAT(2X,'DO YOU WANT SUB FILE NUMBER ',I2,' (YES OR NO)')
      READ(1,130,ERR=115)IOPT
130   FORMAT(1A2)
      IF(IOPT.EQ.'NO') GOTO 190
      IF(IOPT.NE.'YE') GOTO 115
      IF(I.EQ.1) ITRSP=1
      IF(I.EQ.2) IMELE=1
      IF(I.EQ.3) ITWFX=1
      IF(I.EQ.4) IANN =1
      IF(I.EQ.5) IPR  =1
      IF(I.EQ.6) IMIS =1
      IF(IFILE.EQ.ITRSP+IMELE+ITWFX+IANN+IPR+IMIS) GOTO 500
190   CONTINUE
200   CONTINUE
      GO TO 500
300   ITRSP=1
      IMELE=1
      ITWFX=1
      IANN =1
      IPR  =1
      IMIS =1
500   IF(ITRSP.EQ.1) CALL SRCH$$(K$RDWR+K$NDAM,'TRAN  ',6,2,1,IC)
      IF(IMELE.EQ.1) CALL SRCH$$(K$RDWR+K$NDAM,'MEMO  ',6,7,1,IC)
      IF (ITWEX,ELQ,1) CALL SRCHSSCKSROWR#KSNDAMe*TWEX %06e8eLeIC)
      IF(IANN 2£0.1) CALL SRCHSSCKSROWR*KENDAMS PANN  ®eBe9eLeIC) |
      IFCIPR  eF(GeL)D CALL SRCHSSCKSROWRFKSNDAMG PPR SeGeLDoLeIC?
      IF (IMIS o£001) CALL SRCHSSCKSROWREKINDAMS* MIS *eGeLLeIsLIC)
      RETURN
      END
