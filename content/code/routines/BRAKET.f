      SUBROUTINE BRAKET
C      THIS SUBROUTINE PERFORMS THE DEFINING OF THE TIME
C      FRAME TO BE SEARCHED DURING THE SEARCH MODE, IF DESIRED
C
C      DATA DECLARATION AND COMMON BLOCK FOR THE MAIL LOG FILE
C
      COMMON/BLK/ MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,
     1     ADD,TWX,FSC,NRE,DDT,R,PTIT,COUNT,CON
      COMMON/SRC/ KNT,DM,DA,DDD,DTO,DL,IT,D,WA,DW,DT,DRE
     1      ,TFVD,TLVD,FVD,LVD,IEX
      COMMON/FLA/ ITRSP,IMELF,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*4 ATHR(7),TO(8),DLN(5),SUB(21),ROUT(6),PTIT(19),
     1          CON(5),TWX(6,5),FSC(6),NRE(1,3),DDT(30,21),T(21)
     1         ,TIT(24),COUNT,CONT(5),IEX(4,3)
      INTEGER*2 MS,DD(3),IDD(3),ADD(3),R,CWA(4),WA(4)
      INTEGER*2 ITRSP,IMELE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*2 FVD(3),LVD(3),D(3),DM,DDD(3)
      INTEGER*4 DRE,DT(5),DW(5),DL(5),DA(7),IT(24),DTO(8),KNT
      DOUBLE PRECISION DTJ,TF,TL,TJUL,TFVD,TLVD,TIM,TJ
C      DETERMINE THE FIRST DATE
880   WRITE(1,881)
881   FORMAT(' WHAT IS THE FIRST VALID DATE',/,'MMDDYY')
      READ(1,882,ERR=880)FVD
882   FORMAT(3I2)
C      CHECK FOR VALID DATE ENTRY
      IF(FVD(1).GT.12.OR.FVD(2).GT.31) GOTO 880
C      STORE LEGAL ENTRY BY MONTH, DAY, YEAR
      IM=FVD(1)
      ID=FVD(2)
      IY=FVD(3)
C      CONVERT THE FIRST DATE TO JULIAN TIME
      CALL JTIME(IY,IM,ID,0,0,0,TJ)
C      STORE JULIAN (FIRST) TIME
      TFVD=TJ
C      DETERMINE THE LAST DATE OF TIME FRAME
885   WRITE(1,884)
884   FORMAT(' WHAT IS THE LAST VALID DATE',/,'MMDDYY')
      READ(1,882,ERR=885)LVD
C      CHECK FOR VALID ENTRY
      IF(LVD(1).GT.12.OR.LVD(2).GT.31) GOTO 885
C      IF NO LAST ENTRY SPECIFIED, SET TO MAXIMUM DATE
C       DEC. 31, 1999
      IF(LVD(1).EQ.0) LVD(1)=12
      IF(LVD(2).EQ.0) LVD(2)=31
      IF(LVD(3).EQ.0) LVD(3)=99
C      STORE LAST DATE BY MONTH, DAY, YEAR
       IM=LVD(1)
       ID=LVD(2)
       IY=LVD(3)
C      CONVERT THE LAST DATE TO JULIAN TIME
      CALL JTIME(IY,IM,ID,0,0,0,TJ)
C      STORE JULIAN (LAST) TIME
       TLVD=TJ
C       ARE THE DATES ENTERED COMPATIBLE, YES RETURN
C          ELSE DISPLAY ERROR MESSAGE
      IF(TLVD.GE.TFVD) GO TO 886
      WRITE(1,887)
887   FORMAT(' GGERROR IN DATES - PLEASE TRY AGAIN'/)                    ! [?]
      GO TO 880
886   CONTINUE
      RETURN
      END
