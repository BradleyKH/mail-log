     1        R,IDR,INEO,KNT,FIRST,SECOND,TTIT
C
C     DATA DECLARATION BLOCK FOR THE DRAW-EO FILE
C
      INTEGER*4 DRAW(4),TIT(21),PTIT(19),SYS(3),SECT(3),FEOREF(10,2),
     1          DRW(4),EOREF(10,2),EPTIT(19),ETIT(21),EON(2),
     1          IDR(4),KNT,TTIT(19)
      INTEGER*2 DT(3),VEH(2,2),NSHT,SHTN(2),FREV,FNEO,REV,NEO,
     1           EOREV,EDT(3),ERDT(3),EOVEH(2,2),R,INEO,
     1           FIRST,SECOND
C
C
C SYSCOM>KEYS.F       MNEMONIC KEYS FOR FILE SYSTEM (FTN)      31 MAY, 1977
      NOLIST
      INTEGER*2 FINISH,IOPT,IANS,ISHT(2)
1     WRITE(1,2)
2     FORMAT(' HOW MANY DRAWINGS DOES THIS E.O. REFERENCE')
      READ(1,3,ERR=1)IOPT
3     FORMAT(I2)
      IF(IOPT.LE.0) GOTO 1
      DO 300 I=1,IOPT
      REWIND 12
4     WRITE(1,5)
5     FORMAT(' WHAT IS THE DRAWING NUMBER',/,'!',14X,'!')
      READ(1,6,ERR=4)IDR
