      SUBROUTINE REVSC
C
C     DATA DECLARATION AND COMMON BLOCK FOR THE MAIL LOG FILE
C
      COMMON/BLK/ MS,ATHR,DD,TO,DLN,SUB,ROUT,IDD,CWA,CONT,
     1     ADD,TWX,FSC,NRE,DDT,R,PTIT,COUNT,CON
      COMMON/SRC/ KNT,DM,DA,DDD,DTO,DL,IT,D,WA,DW,DT,DRE
     1      ,TFVD,TLVD,FVD,LVD,IEX
      COMMON/FLA/ ITRSP,IMELE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*4 ATHR(7),TO(8),DLN(5),SUB(21),ROUT(6),PTIT(19),
     1          CON(5),TWX(6,5),FSC(6),NRE(1,3),DDT(30,21),T(21)
     1         ,TIT(24),COUNT,CONT(5),IEX(4,3)
      INTEGER*2 MS,DD(3),IDD(3),ADD(3),R,CWA(4),WA(4)
      INTEGER*2 ITRSP,IMELE,ITWFX,IANN,IPR,IMIS,IREAD
      INTEGER*2 FVD(3),LVD(3),D(3),DM,DDD(3)
      INTEGER*4 DRE,DT(5),DW(5),DL(5),DA(7),IT(24),DTO(8),KNT
      DOUBLE PRECISION DTJ,TF,TL,TJUL,TFVD,TLVD,TIM,TJ
C SYSCOM>KEYS.F     MNEMONIC KEYS FOR FILE SYSTEM (FTN)     31 MAY, 1977
      NOLIST
      INTEGER*4 ICOUN
      INTEGER*2 IOPT,FINISH,IA,A(15),IN
C
C     THIS IS THE REVISE ROUTINE FOR THE MAIL LOG FILE
C     THE MAIL LOG DOCUMENT TO BE REVISED OR DELETED
C     KEYED ON THE INPUT DATE AND COUNT CODE
C
C      INITIALIZE FINISHED FLAG
      FINISH=0
C      INITIALIZE CHANGE IN TRANSMITTAL/SPECIFICATION FLAG
      IA=0
C      CLEAR USER TERMINAL SCREEN FOR DISPLAY
      CALL CLEAR
      CALL TIMDAT(A,15)
      IF(A(13).EQ.'JW'.OR.A(13).EQ.'NH'.OR.A(13).EQ.'RJ'.OR.A(13).EQ.
     1 'DK')    GOTO 3
      WRITE(1,4)
4     FORMAT(' SORRY, YOU ARE NOT VALIDATED TO USE THIS MODE.',/,
     1' IF IT IS NECESSARY, PLEASE CONTACT SYSTEM OPERATOR AT EXT. 2621
     1,')
      RETURN
3     WRITE(1,1)
1     FORMAT(' PLEASE ENTER THE INPUT DATE AND COUNT CODE OF THE ',/,
     1' DOCUMENT TO BE REVISED OR DELETED',/,'!',6X,'!!',3X,'!'/)
      READ(1,2,ERR=3)D,ICOUN
2     FORMAT(1X,3I2,2X,I3)
5005  WRITE(1,5000)
5000  FORMAT(1X,'IS THIS A SPECIAL ACTION DUE SUBFILE DELETE REQUEST',/,
     111X,'(YES OR NO)'/)
       READ(1,50)IOPT
       IF(IOPT.EQ.'YE') GOTO 6000
       IF(IOPT.NE.'NO') GOTO 5005
C      DETERMINE SUB FILES TO BE OPENED FOR SEARCH.
       CALL WHERE
C
C      IS THE TRANSMITTAL/SPECIFICATION FLAG SET
C        YES, PERFORM SEARCH AND REVISE OF SUB-FILE TRAN
C
      IF(ITRSP.EQ.0) GOTO 1001
100   READ(6,END=200)MS,ATHR,DD,TO,DLN,SUB,PTIT,
     1 ROUT,IDD,COUNT,CWA,CONT,ADD,TWX,FSC,NRE,DDT
C      IS THIS REVISE COMPLETED
      IF(FINISH.EQ.1) GOTO 125
C      FIND DOCUMENT TO BE REVISED
      IF(ICOUN.NE.COUNT) GOTO 125
      DO 110 I=1,3
      IF(IDD(I).NE.D(I)) GO TO 125
110   CONTINUE
C      CONFIRM RECORD TO BE REVISED
      CALL SHOWC
      WRITE(1,1700)
1700  FORMAT(/,1H0,/,' IS THIS THE CORRECT RECORD TO BE REVISED OR DELET
     1ED',/,' (YES OR NO)')
1800  READ(1,50)IOPT
50    FORMAT(1A2)
      IF(IOPT.EQ.'NO') GOTO 125
      IF(IOPT.NE.'YE') GOTO 1800
1900  WRITE(1,2100)
2100  FORMAT(' IS THIS RECORD 10 BE REVISED OR DELETED o/(
     1   (REV OR CEL)
      READ(C1,50) IOPT
      IF(IOPTSEGs*RE*) GOTO 120
      IF(IOPT.NE.*DE*) GOTO 1900
      FINISH=1
      GOTO 100
C      SET REVISE FLAG
120     R=)
C      PERFORM REVISE OF RECORD ITEM(S)
      CALL INPSC  -                                                   A
C      SET FINISH FLAG TO COMPLETE
      FINISH=1
C      BUILO NEW FILE
125   WRITE CAIMS SATHR GDD, TO,DLN eSUB,PTIT,ROUTs
     1 IDDeCOUNTsCWASCONT oADD eg THX FSCoNRE 2 DOT
      GO TO 160
200   ENDFILE &
      CALL SKCHSSCKSCLOSs* TRAN %e6909000)
      CALL SRCH$$(KSDELEs* TRAN 6000000)
         CALL CNAM$$(PREVS  %eGeTTRAN  %eL9IC)
      CALL SRCH$$(KSROWR*KSNDAMG®REVS  %eBe4,1,IC)
C
C      IS THE MEMO/LETTER SUB FILE FLAG SET
C         YESs SEARCH AND REVISE THE SUB-FILE MEMO
C
C
1001  IF(FINISH-EG.1) GOTO 3000
        IF(IMELE*EQ-0) GOTO 1002
       IN=11
       GO TO 2000
1002   IF(FINISH.EQ.1) GOTO 2000
       IF(ITWEX.EQ.0) GOTO 1003
       IN=12
       GOTO 2000                                                      A
1003    IF(FINISH.EQ.1) GOTO 3000
       IF(IANN.EQ.0) GOTO 1004
       IN=13
       GO TO 2000
C 1004 IFCFINISHeFGe1) GOTO 3000
       IF(IPR.EQ.0) GOTO 1005
       IN=14
       GOTO 2000
1005   IF (FINISHSEO.1) GOTO 3000
       IF(IMIS,ER.0) GOTO 3000 .
       IN=15
2000   CONTINUE
101   READ CIN,END=201 MS, ATHR,DD, TO,DLN,SUB,PTITs
     1 ROUTsILDsCOUNTsCWAsCONT sADDs TWXoFSCeNRE
C      1S THIS. REVISE COMPLETED
      IF(FINISH.EQ.1) GOTO 126
      FIND DOCUMENT TO BE REVISED
      IF(COUNT.NE.ICOUN) GOTO 126
      DO 111 12143.
      IF(IOO(I) NED(T))? GO TO 126
111   CONTINUE
      IF(ITRSP.EG20) GOTO 21
      ITRSP=0
      TA=1
C      CONFIRM RECORD TO BE REVISED
21    CALL SHOWC
      IF(IA.EQ.0) GOTO 31
      TTRSP=1
      TA=0
31    WRITE (191700)
2801  READ(19S0)10PT
      IF(IOPT.EQ.*NO*) GOTO 126
      IF(IOPTNES*YE*)  GOTO 1401
1901  WRITE(1,2100)
      READC1(50) OPT
      IF(IOPT.EQ.*RE®) GOTO 121
      IF(IOPT.NE.*DE*) GOTO 1901
      FINISH=1
      GOTO 161
C      SET REVISE FLAG
121     R=1
C      PERFORM REVISE OF RECORD ITEM(S)
      CALL INPSC
C      SET FINISH FLAG TO COMPLETE
      FINISH=1
C      BUILD NEW FILE
126   WRITE(8)MS,ATHR,DD,TO,DLN,SUB,PTIT,ROUT,
     1 IDD,COUNT,CWA,CONT,ADD,TWX,FSC,NRE
      GO TO 101
201   ENDFILE 8
      IF(IN.EQ.11) GOTO 2001
      IF(IN.EQ.12) GOTO 2002
      IF(IN.EQ.13) GOTO 2003
      IF(IN.EQ.14) GOTO 2004
      IF(IN.EQ.15) GOTO 2005
2001  CALL SRCH$$(K$CLOS,'MEMO  ',6,0,0,0)
      CALL SRCH$$(K$DELE,'MEMO  ',6,0,0,0)
        CALL CNAM$$('REVS  ',6,'MEMO  ',6,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'REVS  ',6,4,1,IC)
      GO TO 1002
2002  CALL SRCH$$(K$CLOS,'TWFX  ',6,0,0,0)
      CALL SRCH$$(K$DELE,'TWFX  ',6,0,0,0)
        CALL CNAM$$('REVS  ',6,'TWFX  ',6,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'REVS  ',6,4,1,IC)
      GO TO 1003
2003  CALL SRCH$$(K$CLOS,'ANN   ',6,0,0,0)
      CALL SRCH$$(K$DELE,'ANN   ',6,0,0,0)
        CALL CNAM$$('REVS  ',6,'ANN   ',6,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'REVS  ',6,4,1,IC)
      GO TO 1004
2004  CALL SRCH$$(K$CLOS,'PR    ',6,0,0,0)
      CALL SRCH$$(K$DELE,'PR    ',6,0,0,0)
        CALL CNAM$$('REVS  ',6,'PR    ',6,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'REVS  ',6,4,1,IC)
      GO TO 1005
2005  CALL SRCH$$(K$CLOS,'MIS   ',6,0,0,0)
      CALL SRCH$$(K$DELE,'MIS   ',6,0,0,0)
        CALL CNAM$$('REVS  ',6,'MIS   ',6,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'REVS  ',6,4,1,IC)
C
3000   RETURN
6000   CALL SRCH$$(K$RDWR+K$NDAM,'ACTD  ',6,5,1,IC)
      REWIND 9
6010   READ(9,END=7000)ATHR,DLN,PTIT,IDD,COUNT,ADD,FSC,NRE
      IF(FINISH.EQ.1) GOTO 6050
      IF(COUNT.NE.ICOUN) GOTO 6050
      DO 6020 I=1,3
      IF(IDD(I).NE.D(I)) GOTO 6050
6020   CONTINUE
      WRITE(1,6025)PTIT,DLN,FSC,IDD,COUNT,ATHR,NRE,ADD
6025   FORMAT(1X,19A4,/,1X,4A4,A2,5X,2A4,A2,'/',2A4,A2,5X,
     1 2(I2,'-'),I2,2X,I3,/,1X,7A4,2X,3(A3,1X),7X,2(I2,'-'),I2)
6028   WRITE(1,1700)
      READ(1,50,ERR=6028)IOPT
      IF(IOPT.EQ.'NO') GOTO 6050
      IF(IOPT.NE.'YE') GOTO 6028
      FINISH=1
6030   WRITE(1,2100)
      READ(1,50) IOPT
      IF(IOPT.EQ.'DE') GOTO 6010
      IF(IOPT.NE.'RE') GOTO 6030
6035   WRITE(1,6040)
6040   FORMAT(1X,'REVISE OPTIONS:',/,7X,'1.  AUTHOR',/,
     17X,'2.  DOCUMENT/LETTER NUMBER',/,7X,'3.  ACTION DUE DATE',/,
     17X,'4.  FILE SYSTEM CODE',/,7X,'5.  RESPONSIBLE ENGINEER',/,
     11X,'ENTER NUMBER ONLY'/)
      READ(1,6047,ERR=6035)IOPT
6047   FORMAT(I2)
      IF(IOPT.EQ.1) GOTO 6042
      IF(IOPT.EQ.2) GOTO 6043
      IF(IOPT.EQ.3) GOTO 6044
      IF(IOPT.EQ.4) GOTO 6045
      IF(IOPT.EQ.5) GOTO 6046
      GO TO 6035
6042   WRITE(1,6052)
6052   FORMAT(1X,'ENTER AUTHOR',/,'!',28X,'!'/)
      READ(1,6062,ERR=6042)ATHR
6062  FORMAT(1X,7A4)
      GO TO 6048
6043  WRITE(1,6053)
6053  FORMAT(1X,'ENTER DOC./LETTER NUMBER',/,'!',18X,'!'/)
      READ(1,6063,ERR=6043)DLN
6063  FORMAT(1X,4A4,A2)
      GO TO 6048
6044  WRITE(1,6054)
6054  FORMAT(1X,'ENTER ACTION DUE DATE',/,'!MMDDYY!'/)
      READ(1,6064,ERR=6044)ADD
6064  FORMAT(1X,3I2)
      GO TO 6048
6045  WRITE(1,6055)
6055  FORMAT(1X,'ENTER FILE SYSTEM CODE',/,2('!',10X,'!')/)
      READ(1,6065,ERR=6045)FSC
6065  FORMAT(2(1X,2A4,A2,1X))
      GO TO 6048
6046  WRITE(1,6056)
6056  FORMAT(1X,'ENTER RESPONSIBLE ENGINEER',/,3('!   !')/)
      READ(1,6066,ERR=6046)(NRE(1,J),J=1,3)
6066  FORMAT(3(1X,A3,1X))
6048  WRITE(1,6025)PTIT,DLN,FSC,IDD,COUNT,ATHR,NRE,ADD
6050  WRITE(8)ATHR,DLN,PTIT,IDD,COUNT,ADD,FSC,NRE
      GO TO 6010
7000  CALL SRCH$$(K$CLOS,'ACTD  ',6,0,0,0)
      CALL SRCH$$(K$CLOS,'REVS  ',6,0,0,0)
      CALL SRCH$$(K$DELE,'ACTD  ',6,0,0,0)
      CALL CNAM$$('REVS  ',6,'ACTD  ',6,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'REVS  ',6,4,1,IC)
      RETURN
      END
