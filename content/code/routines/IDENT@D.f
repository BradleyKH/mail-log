      SUBROUTINE IDENT
C
C     THIS ROUTINE KEEPS TRACK OF WHO ACCESSED THE CALLING
C     PROGRAM LAST
C
      INTEGER*2 ARRAY(15)
C SYSCOM>KEYS.F       MNEMONIC KEYS FOR FILE SYSTEM (FTN)      31 MAY, 1977
      NOLIST
      CALL BREAK$(.TRUE.)
      CALL TIMDAT(ARRAY,15)
C
C     OPEN TEMP FILE (FUNIT 16)
C
      CALL SRCH$$(K$NDAM+K$RDWR,'TUSER',5,16,1,IC)
C
C     OPEN USER FILE (FUNIT 15)
C
      CALL SRCH$$(K$NDAM+K$RDWR,'USER',4,15,1,IC)
C
C     NOW WRITE USERS LOGIN ID, DATE (MMDDY), TIME, AND USER NUMBER
C
      AMIN=ARRAY(4)
      AH=AMIN/60.0
      IH=AH
      IMM=IH*60
      IMIN=AMIN
      IDM=IMIN-IMM
25    WRITE(20,1)(ARRAY(I),I=13,15),IH,IDM,ARRAY(5),
     1             (ARRAY(I),I=1,3),ARRAY(12)
1     FORMAT(3A2,2(I3,':'),I3,1X,2(A2,'/'),A2,I3)
2     FORMAT(3A2,2(I3,1X),I3,1X,2(A2,1X),A2,I3)
C
C     NOW COPY THE CONTENTS OF USER TO TUSER
C
      READ(19,2,END=50)(ARRAY(I),I=13,15),IH,IDM,ARRAY(5),
     1                 (ARRAY(I),I=1,3),ARRAY(12)
      GO TO 25
50    CALL SRCH$$(K$CLOS,'USER',4,0,0,0)
      CALL SRCH$$((KSCLOS, "TUSER® 95900090)
      CALL SRCH$$(KSDELE, *USER% 24500090)
       CALL CNAM$$(*TUSER® e S, USER 9 49 IC)
      CALL BREAK$ (eFALSE.)
      RETURN
      END
