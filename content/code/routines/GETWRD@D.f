C     FETCH ONE 'WORD' FROM BUFFER FILLED BY RDCOM
C
C
      SUBROUTINE  GETWRD(BUF,NAME,LEN)
C
      COMMON /X/ PEDL
C
      INTEGER BUF(1),PEDL,NAME(1),CHAR,
     +     ANL,ACOMMA,ASCOL,ASP,ASPSP
C
C     ANL,ACOMMA,ASCOL,ASP,ASPSP
C         ARE OCTAL
C     212,254,273,240,120240
C
      DATA ANL,ACOMMA,ASCOL/138,172,187/,
     +     ASP,ASPSP/160,2H  /
C
      DO 100 I=1,3
100   NAME(I)=ASPSP
C
      N=1
      IF(BUF(1).NE.ASP) GO TO 200
      DO 999 I=2,77
      II=I-1
      BUF(II)=BUF(I)
999   CONTINUE
200   CHAR=BUF(PEDL)
      PEDL=PEDL+1
      IF(PEDL.GT.77)  RETURN
      IF(CHAR.EQ.ANL)  GOTO 400
      IF(CHAR.EQ.ASP.OR.CHAR.EQ.ACOMMA.OR.CHAR.EQ.ASCOL)  GOTO 300
      IF(N.GT.LEN)  GOTO 200
      I=(N+1)/2
      J=N-2*(N/2)
      N=N+1
      IF(J.EQ.1) GOTO 250
      NAME(I)=LT(NAME(I),8) + CHAR
      GOTO 200
250   NAME(I)= RTCNAME(I 298) + LSC(HAR,8)
      GOTO 208
C
300   CHAR=BUF(PEDL)
      IF(CHAR.EQ.ANL)  GOTO 400
      IF (CHAR NE «ASP.AND.CHAR.NE.ACOMMA SAND eCHARSNESASCOL) RETURN
      PEOL=PEOL41
      GOTO 300                                       .

400   PEQL=77
      RETURN
C
      END
