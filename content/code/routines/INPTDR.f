520   READ(6,END=1010) TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
510   FORMAT(1X,3A4,A2)
      DO 530 I=1,4
      IF(DIR(I).NE.DIRR(I)) GOTO 580
530   CONTINUE
      WRITE(1,540)
540   FORMAT(' THIS DIR/REPORT IS ALREADY IN THE DATA FILE'/)
      CALL SHOWDR
545   WRITE(1,550)
550   FORMAT(1H0,/,' DO YOU WISH TO REVISE (YES OR NO)'/)
      READ(1,560,ERR=545) IOPT
560   FORMAT(1A2)
      IF(IOPT.EQ.'NO') GOTO 1005
      IF(IOPT.NE.'YE') GOTO 545
      R=1
      CALL INPSDR
      WRITE(10) TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
570   READ(6,END=600) TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
      WRITE(10) TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
      GO TO 570
580   WRITE(10) TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
       GO TO 520
600   CALL SRCH$$(K$CLOS,'TEMP  ',6,0,0,0)
      CALL SRCH$$(K$CLOS,'DIR   ',6,0,0,0)
      CALL SRCH$$(K$DELE,'DIR   ',6,0,0,0)
        CALL CNAM$$('TEMP  ',6,'DIR   ',6,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'DIR   ',6,2,IT,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'TEMP  ',6,6,IT,IC)
      GO TO 900
1010  R=0
      DO 800 J=1,4
      DIR(J)=DIRR(J)
800   CONTINUE
      CALL INPSDR
      WRITE(60)TIT,PTIT,DIRRoDT oS YS eWANSVEH OREVARDAT
1005  CALL SRCH$$(KSCLOSs*TEMP   6909090)
      CALL SRCH$$(KSDELEs*TEMP  %e6409000)
      CALL SRCH$$(KEROWR+KENDAMe*® TEMS 8 %eGGG,IT IC)
900   WRITEC1(1001)
1001  FORMAT(' IS THERE FURTHER INFCRMATICN TO GE INPUT'%,
     1  CYES OR NO)*/)
      READ(141002) TANS
      REWIND 6
C     IF CTANScsEGe*N*) RETURN
      IF(TANS.NE.*Y*) GOTO 900
1002  FORMAT(1A1)
      GOTO 500°
      END         .
