      SUBROUTINE ARCDR
C
C     COMMON BLOCK FOR THE DIR FILE
C
      COMMON TIT,PTIT,DIR,RPT,DT,SYS,WAN,CON,ID,VEH,ACT,R
      COMMON COMP,REV,RDAT,WA
C
C
C     DATA DECLARATION BLOCK FOR THE DIR FILE
C
      INTEGER*4 TIT(21),PTIT(19),DIR(4),RPT(4),SYS(3),CON(5),ID,ACT
      INTEGER*4 COMP(21)
      INTEGER*2 DT(3),WAN(4),VEH(2,2),R,REV,RDAT(3),WA(4)
C
C SYSCOM>KEYS.F       MNEMONIC KEYS FOR FILE SYSTEM (FTN)      31 MAY, 1977
      NOLIST
C
C
C     ARCHIVE ROUTINE FOR THE DIR FILE
C
      INTEGER*4 IDR(4)
      INTEGER*2 IT,IC
C     VALIDATE THE INCOMMING USER
C
      CALL IDUSER(IAI)
      IF(IAI.EQ.'SY') GO TO 10
      WRITE(1,300)
300   FORMAT('GGSORRY YOU ARE NOT VALIDATED TO USE THIS',
     11X'ROUTINE',/,'IF IT IS NEEDED CONTACT YOUR SYSTEMS',
     11X' PROGRAMMER AT EXT 2621'/////)
      RETURN
10    WRITE(1,1)
1     FORMAT(' WELCOME TO THE DIR-REPORT FILE ARCHIVE ROUTINE',/
     1' HOW MANY DOCUMENTS DO YOU WISH TO ARCHIVE',/)
      READ(1,2,ERR=10)IKNT
2     FORMAT(I5)
      IF(IKNT.EQ.0) RETURN
      CALL SRCH$$(K$RDWR+K$NDAM,'INACT ',6,5,IT,IC)
C
C     PLACE THE ARCHIVE FILE AT THE EOF MARKER
C
50    READ(9,END=75)TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
      GO TO 50
75    DO 9999 ILOOP=1,IKNT
82    WRITE(1,80)
80    FORMAT(' WHAT IS THE DIR-REPORT NUMBER OF THE DOCUMENT ',
     1' YOU WISH TO ARCHIVE',/)
      READ(1,81,ERR=82)IDR
81    FORMAT(3A4,A2)
100   READ(6,END=200)TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
      DO 150 I=1,4
      IF(IDR(I).NE.DIR(I)) GO TO 125
150   CONTINUE
      WRITE(9)TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
      GO TO 100
125   WRITE(10)TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
      GO TO 100
200   CALL SRCH$$(K$CLOS,'DIR   ',6,0,0,0)
      CALL SRCH$$(K$DELE,'DIR   ',6,0,0,0)
      CALL SRCH$$(K$CLOS,'TEMP  ',6,0,0,0)
        CALL CNAM$$('TEMP  ',6,'DIR   ',6,IC)
         CALL SRCH$$(K$RDWR+K$NDAM,'DIR   ',6,2,IT,IC)
      CALL SRCH$$(K$RDWR+K$NDAM,'TEMP  ',6,6,IT,IC)
9999  CONTINUE
      ENDFILE 9
      CALL SRCH$$(K$CLOS,'INACT ',6,0,0,0)
      RETURN
      END
