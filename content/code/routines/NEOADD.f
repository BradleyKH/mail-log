7     WRITE(1,8)
8     FORMAT(' HOW MANY SHEETS OF THIS DRAWING ARE REFERENCED BY THIS ',
     1'E.O.')
      READ(1,3,ERR=7)IANS
      IF(IANS.LE.0) GOTO 7
      DO 250 J=1,IANS
12    WRITE(1,13)
13    FORMAT(' WHAT IS THE SHEET NUMBER:  EXAMPLE SHEET# 2.1   !02!!10!'  ! [?]
