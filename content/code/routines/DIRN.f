      SUBROUTINE DIRN
C
C     COMMON BLOCK FOR THE DIR FILE
C
      COMMON TIT,PTIT,DIR,RPT,DT,SYS,WAN,CON,ID,VEH,ACT,R
      COMMON COMP,REV,RDAT,WA
C
C
C     DATA DECLARATION BLOCK FOR THE DIR FILE
C
      INTEGER*4 TIT(21),PTIT(19),DIR(4),RPT(4),SYS(3),CON(5),ID,ACT
      INTEGER*4 COMP(21)
      INTEGER*2 DT(3),WAN(4),VEH(2,2),R,REV,RDAT(3),WA(4)
C
C
C
C     THIS ROUTINE LOCATES A DOCUMENT WITH A SPECIFIED
C     DIR-REPORT NUMBER
C
      INTEGER*4 KNT,IDIR(4)
      KNT=0
3     WRITE(1,1)
1     FORMAT(' WHAT IS THE DESIRED DIR-REPORT NUMBER'/)
      READ(1,2,ERR=3) IDIR
2     FORMAT(3A4,A2)
      WRITE(1,2)IDIR
100   READ(6,END=200)TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
      DO 1000 I=1,4
      IF(IDIR(I).NE.DIR(I)) GO TO 100
1000  CONTINUE
      CALL FMAIN
      GO TO 100
200   RETURN
      END
