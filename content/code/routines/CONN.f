      SUBROUTINE CONN
C
C     COMMON BLOCK FOR THE DIR FILE
C
      COMMON TIT,PTIT,DIR,RPT,DT,SYS,WAN,CON,ID,VEH,ACT,R
      COMMON COMP,REV,RDAT,WA
C
C
C     DATA DECLARATION BLOCK FOR THE DIR FILE
C
      INTEGER*4 TIT(21),PTIT(19),DIR(4),RPT(4),SYS(3),CON(5),ID,ACT
      INTEGER*4 COMP(21)
      INTEGER*2 DT(3),WAN(4),VEH(2,2),R,REV,RDAT(3),WA(4)
C
C SYSCOM>KEYS.F       MNEMONIC KEYS FOR FILE SYSTEM (FTN)      31 MAY, 1977
      NOLIST
C
C
C     THIS ROUTINE LOCATES ALL DOCUMENTS WITH A SPECIFIED CONTRACT NUMBER
C
      INTEGER*4 DC(5),KNT
      INTEGER*2 IT,IC
      KNT=0
1     WRITE(1,3)
3     FORMAT(' WHAT IS THE DESIRED CONTRACT NUMBER',/)
      READ(1,2,ERR=1)DC
2     FORMAT(5A4)
      CALL SRCH$$(K$RDWR+K$NDAM,'CTAB  ',6,14,IT,IC)
30     READ(18,40,END=200)WA,CON
40    FORMAT(5X,4A2,2X,5A4)
      DO 45 I=1,5
      IF(CON(I).NE.DC(I)) GOTO 30
45    CONTINUE
100   READ(6,END=90)TIT,PTIT,DIR,DT,SYS,WAN,VEH,REV,RDAT
      IF(WA(1).EQ.'38'.AND.WA(2).EQ.'04'.OR.WA(2).EQ.'09') GOTO 660
      IF(WAN(1).NE.WA(1)) GOTO 100
      IF(WAN(2).NE.WA(2)) GOTO 100
      GO TO 701
660   DO 665 I=1,4
      IF(WAN(I).NE.WA(I)) GOTO 100
665    CONTINUE
701   CALL CMAIN
      KNT=KNT+1
      GO TO 100
90    REWIND 6
      GO TO 30
200   WRITE(1,250)KNT,DC
250   FORMAT(' THERE ARE'I9' DOCUMENTS WITH A CONTRACT',
     1' NUMBER OF '5A4)
       CALL SRCH$$(K$CLOS,'CTAB  ',6,0,0,0)
      RETURN
      END
